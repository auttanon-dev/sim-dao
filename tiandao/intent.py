def plan_wants(ch, materials):
    """ตั้ง ch.wants จาก "สูตรที่ใกล้จะทำได้ที่สุด" ของสายที่ตัวเองเดินอยู่

    ต้องเรียกก่อน weigh() (ดู Sim.step) ไม่ใช่ข้างใน — weigh ต้องอ่านอย่างเดียว ไม่แก้สถานะ
    ตัวละคร ไม่งั้นการทดสอบ/การจำลองซ้ำจะเชื่อถือไม่ได้

    เดิม wants ถูกตั้งตอน "หลอมพลาด" เท่านั้น พอเจตนาฉลาดขึ้นจนไม่เดินไปหลอมทั้งที่ของไม่ครบ
    ความล้มเหลวก็หายไป และระบบตามหาวัตถุดิบก็ตายไปด้วย — จึงต้องคิดก่อนลงมือ ไม่ใช่รอให้พลาด
    """
    if ch.alch_rank < 0 and ch.forge_rank < 0 and ch.archetype != "ช่างหลอม":
        return
    tcap = min(ch.tier, 2)
    for is_pill, rank in ((True, ch.alch_rank), (False, ch.forge_rank)):
        if rank < 0 and ch.archetype != "ช่างหลอม":
            continue
        _name, lack = materials.plan_shortfall(ch.mat_stock, is_pill, rank, tcap)
        for m, q in lack.items():
            ch.wants[m] = max(ch.wants.get(m, 0), q)
    if ch.forge_rank >= 0 or ch.archetype == "ช่างหลอม":
        # เครื่องมือค่ายกลเป็นงานโลหะ — ช่างสายเหล็กเป็นคนที่ตามหาของพวกนี้
        _t, lack = materials.plan_array_shortfall(ch.mat_stock, tcap)
        for m, q in lack.items():
            ch.wants[m] = max(ch.wants.get(m, 0), q)
    if len(ch.wants) > C.WANT_MAX:
        for m in list(ch.wants)[:-C.WANT_MAX]:
            ch.wants.pop(m, None)


