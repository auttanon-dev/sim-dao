"""แดนเซียนสาขา — "สามพันโลก" ในความหมายที่จำลองไหว

ที่มาในโลกของเรื่อง: ผู้บำเพ็ญที่ออกค้นแดนลับในโลกเซียนแล้วรอดกลับมา ไม่ได้กลับมามือเปล่า —
บางคนได้วิชาที่ไม่มีใครเคยเห็น แล้วตั้งสำนักของตัวเองขึ้นในดินแดนที่ตัวเองค้นพบ ดินแดนพวกนั้น
ถูกเรียกรวมๆ ว่า "แดนเซียนสาขา" ส่วนโลกมนุษย์กับแดนวัฒนธรรมข้างเคียงถูกเรียกว่า "แดนเบื้องล่าง"

มีกี่แดนกันแน่ — สามตัวเลขที่ไม่เท่ากันและไม่ควรสับสน
---------------------------------------------------------------------------------------------
  · **คลังชื่อ 108 แดน** — `build()` ผลิตชื่อกับสายวิชาไว้ครบ 108 และ places.py สร้างผัง
    สถานที่ไว้ให้ทั้ง 108 ตั้งแต่ตอน import (540 แห่ง) นี่คือ *เพดานความจุ* ไม่ใช่จำนวนจริง
  · **หว่านตั้งต้น C.BRANCH_REALMS แดน** (ตอนนี้ 36) — Sim.__init__ หยิบจากคลังมาเท่านี้
    ที่เหลือปล่อยว่างไว้ให้โลกงอกเอง เพราะหว่านครบ 108 ตั้งแต่วันแรกทำให้ประชากรเจือจาง
  · **งอกเพิ่มระหว่างซิม** — ผู้รอดจากแดนลับต้นกำเนิดไปตั้งสาขาของตัวเอง
    (worldtree._found_branch) จนถึงเพดานจำนวนโลกรวมที่ C.TREE_BRANCH_CAP
วัดจริงที่ 60,000 เหตุการณ์: 36 ตั้งต้น + 6 ที่โลกตั้งเอง = 42 แดน (ดู test_worldtree.py)

ที่ตัดสินใจไว้ตรงๆ สองข้อ เพื่อให้แต่ละสาขาเป็นของจริงโดยไม่ทำให้ซิมพัง
---------------------------------------------------------------------------------------------
1. **แต่ละสาขามีประชากรของตัวเองจริง** ไม่ใช่ชื่อลอยๆ ในตาราง — คนในนั้นเกิด ตาย ฝึกวิชา ตั้งสำนัก
   เดินทาง และข้ามฟ้าได้เหมือนทุกแดน แต่ประชากรตั้งต้นน้อยกว่าแดนหลักมาก (ดู C.BRANCH_CAST)
   เพราะมันคือ "สำนักที่ขยายเป็นดินแดน" ไม่ใช่อารยธรรมเต็มใบ
2. **แต่ละสาขาที่หว่านตั้งต้นมีผังสถานที่ของตัวเอง** วางเป็นวงแหวนรอบแดนเซียนกลาง และเข้าออก
   ได้ทางเดียวคือผ่านแดนเซียนกลาง (ดู realm_map.py) เดิมทุกสาขาใช้ผังร่วมกับแดนเซียนหลัก
   (place_key = 1) ซึ่งประหยัดแต่ทำให้การเดินทางข้ามสาขาใช้เวลาเท่าเดินข้ามเมือง — ตำแหน่ง
   จึงไม่มีความหมาย  ข้อยกเว้นที่ยังเหลืออยู่: สาขาที่ **งอกระหว่างซิม** ยังได้ place_key = 1
   คือใช้ผังร่วมกับแดนเซียนหลักแบบเดิม เพราะผังวงแหวนถูกสร้างไว้ล่วงหน้าตอน import เท่านั้น

สิ่งที่ทำให้แต่ละสาขาไม่เหมือนกัน คือ `skill_line` — สายวิชาประจำแดน ซึ่งไปมีผลจริงตอนคนในแดนนั้น
เลือกวิชาที่จะฝึก (ดู sim.py handler "ฝึกวิชา") สาขาสายกระบี่กับสาขาสายค่ายกลจึงผลิตคนคนละแบบ
"""
import hashlib
from typing import List, NamedTuple

from .skills import SKILLS

# คำประกอบชื่อแดน — ผสมกันได้ 8 x 9 x 12 = 864 แบบ พอสำหรับ 108 ชื่อที่ไม่ซ้ำกัน
_PREFIX = ["บูรพา", "ประจิม", "อุดร", "ทักษิณ", "มัชฌิม", "อาคเนย์", "พายัพ", "อีสาน"]
_MID = ["เมฆ", "ดารา", "วารี", "อัคคี", "ศิลา", "วายุ", "อสนี", "หิมะ", "สนธยา"]
_SUFFIX = ["ลึกลับ", "นิรันดร์", "ต้องห้าม", "เร้นกาย", "สาบสูญ", "รุ่งอรุณ",
           "อัสดง", "พันชั้น", "เก้าฟ้า", "ไร้เงา", "ศักดิ์สิทธิ์", "ลี้ลับ"]

# ที่มาของผู้ก่อตั้ง — ใช้เป็นสำนวนในนิยาย และบอกได้ว่าสาขานี้เกิดจากอะไร
_ORIGIN = [
    "ผู้รอดจากแดนลับต้นกำเนิด",
    "ศิษย์ที่แยกตัวจากสำนักเดิม",
    "นักบุกเบิกที่ตามรอยต้นไม้โลก",
    "ผู้พเนจรที่ได้วิชาจากซากบรรพกาล",
    "ตระกูลเก่าที่หนีศึกขึ้นมาตั้งรกราก",
]

def _viable_lines():
    """สายวิชาที่ใช้เป็น "วิชาประจำแดน" ได้จริง — ต้องมีให้เรียนหลายวิชาและไต่ได้หลายเกรดในชั้นของ
    แดนเซียน (tier <= 1) ไม่งั้นคนในแดนนั้นจะไม่มีวันได้เจอวิชาประจำแดนของตัวเองเลย

    วัดจริงตอนตั้งค่าแรกที่สุ่มจากทั้ง 49 สาย: มีแค่ 18% ของสาขาที่วิชาประจำแดนโผล่มาเกิน 15% ของ
    วิชาที่คนในแดนรู้ เพราะสายอย่าง "วัชระ" มีวิชาเดียวและอยู่เกรด 2 เท่านั้น คนขั้นต้นจึงไม่มีสิทธิ์
    หยิบได้เลยตลอดชีวิต — เหลือ 16 สายที่ผ่านเกณฑ์ ซึ่งพอให้แต่ละสาขาต่างกันจริงและเรียนได้จริง
    """
    out = []
    for line in sorted({s[1] for s in SKILLS}):
        sk = [s for s in SKILLS if s[1] == line and s[2] <= 1]
        if len(sk) >= 3 and len({s[3] for s in sk}) >= 2:
            out.append(line)
    return out


_LINES = _viable_lines()


class Branch(NamedTuple):
    name: str
    skill_line: str      # สายวิชาประจำแดน — ทำให้แต่ละสาขาผลิตคนคนละแบบจริง
    origin: str


def _pick(seed: str, pool):
    """เลือกแบบ deterministic จากชื่อ ไม่ใช้ rng ของซิม — สร้างโลกซ้ำได้เป๊ะและไม่เลื่อน seed เดิม"""
    h = int(hashlib.sha256(seed.encode("utf-8")).hexdigest(), 16)
    return pool[h % len(pool)]


def build(n: int = 108) -> List[Branch]:
    """รายชื่อแดนเซียนสาขาทั้งหมด — คงที่เสมอสำหรับ n เดียวกัน ไม่ขึ้นกับ seed ของโลก"""
    out, used = [], set()
    i = 0
    while len(out) < n:
        name = (f"แดนเซียน{_PREFIX[i % len(_PREFIX)]}"
                f"{_MID[(i // len(_PREFIX)) % len(_MID)]}"
                f"{_SUFFIX[(i // (len(_PREFIX) * len(_MID))) % len(_SUFFIX)]}")
        i += 1
        if name in used:
            continue
        used.add(name)
        out.append(Branch(name=name,
                          skill_line=_pick(name + "|line", _LINES),
                          origin=_pick(name + "|origin", _ORIGIN)))
    return out
