def places_in(world_key, include_secrets=True):
    """ดึงรายชื่อสถานที่ในแดนที่กำหนด"""
    res = []
    for i, p in enumerate(PLACES):
        if p[1] == world_key:
            if not include_secrets and p[3] == "แดนลับ":
                continue
            res.append(i)
    return res


def secret_realms_of(world_key):
    """ดึงรายชื่อแดนลับทั้งหมดที่แตกแขนงเฉพาะในแดนนั้นๆ (ไม่เชื่อมข้ามแดน)"""
    return [i for i, p in enumerate(PLACES) if p[3] == "แดนลับ" and p[6] == world_key]


def place_index(name: str) -> int:
    """ค้นหา index ของสถานที่จากชื่อ"""
    for i, p in enumerate(PLACES):
        if p[0] == name:
            return i
    raise KeyError(f"Place '{name}' not found in PLACES")


