"""สมการของโลกจริง ที่โลกนี้ยืมมาใช้ — และเหตุผลว่าทำไมถึงยืมอันนั้น

ทำไมต้องมีไฟล์นี้: ตัวเลขตัดสินใจของเอนจินเกือบทั้งหมดเคยเป็นค่าที่ "จูนมาจากการวัดผล"
— วัดแล้วขยับ วัดแล้วขยับ (`SECLUDE_W_BASE` 6 -> 10, `MARA_BOLD_PER_KILL` 0.035 ...)
วิธีนั้นได้ผลในระยะสั้นแต่มีจุดอ่อนสามข้อ
  1. เลขไม่ได้มาจากอะไร แก้กลไกทีไรต้องจูนใหม่ทุกที
  2. รูปแบบของสมการมักผิดตั้งแต่ต้น แล้วถูกกลบด้วยการ clamp — เช่นโอกาสข้ามขั้นเดิมเป็น
     เส้นตรงที่พุ่งทะลุ 1 แล้วถูกบีบกลับที่ 0.95 แปลว่า **ตัวบีบคือสิ่งที่ตัดสินผลจริง**
     ไม่ใช่สมการ (วัดจริง: อัตราสำเร็จรวม 81.3% โดยส่วนใหญ่ชน 0.95)
  3. เกณฑ์ตัดแข็ง (`acc >= need*0.9`) ตอบได้แค่ "พอหรือยัง" ตอบไม่ได้ว่า "ควรลงมือเมื่อไร"
     วัดจริง: การข้ามขั้น 3,629 ครั้ง จบด้วย "สะสมต่อ" 1,894 ครั้ง = 52% ของการลงมือ
     เป็นการลงมือก่อนเวลา

สมการจากโลกจริงแก้ทั้งสามข้อพร้อมกัน เพราะมันมีรูปแบบที่ถูกต้องอยู่แล้วโดยธรรมชาติ
(มีขอบเขต 0-1 เองโดยไม่ต้อง clamp · อิ่มตัวเอง · มีจุดเหมาะสมที่หาด้วยอนุพันธ์ได้)

สิ่งที่ยืมมา
  · การข้ามกำแพงพลังงาน (Boltzmann/logit)  -> โอกาสทะลวงขั้น
  · การหาจุดเหมาะสมด้วยอนุพันธ์            -> ควรทะลวงขั้นเมื่อไร
  · การเติบโตแบบลอจิสติก                   -> พลังฟ้าดินของโลกฟื้นตัวยังไง
  · กฎกำลังสองของแลนเชสเตอร์               -> ผลของสงครามระหว่างหมู่คน

สิ่งที่ **ไม่** ยืมมา และเหตุผล
  · พลังงานจลน์/โมเมนตัมในการต่อสู้ — "พลัง" ของตัวละครไม่ใช่มวลคูณความเร็ว การเขียน
    ½mv² ลงไปจะเป็นการแปะสัญลักษณ์ฟิสิกส์บนของที่ไม่ใช่ฟิสิกส์ ได้ความขลังแต่ไม่ได้ความจริง
  · กฎกำลังสองผกผันกับชื่อเสียง/ข่าวลือ — ใช้ได้ถ้าโลกมีพิกัดจริง แต่โลกนี้ใช้กราฟสถานที่
    (ดู places.py) ระยะทางที่มีความหมายคือจำนวนก้าวบนกราฟ ไม่ใช่ระยะยุคลิด
  · สมการเชิงอนุพันธ์ของประชากรทั้งระบบ — โลกนี้เดินด้วยเหตุการณ์ทีละอัน (event-driven)
    การยัด ODE ของทั้งระบบเข้าไปจะขัดกับแกนกลางของเอนจิน และทำให้ความคงที่ (determinism)
    ตรวจยากขึ้นโดยไม่ได้อะไรกลับมา

ทุกฟังก์ชันในไฟล์นี้ **ไม่ดึง rng เลย** — เป็นคณิตศาสตร์ล้วน ผลเหมือนเดิมทุกครั้งที่เรียก
ความสุ่มของโลกยังอยู่ที่เดิมคือ `rng.random() < p` ในผู้เรียก
"""
import math

_ALMOST_ONE = math.nextafter(1.0, 0.0)    # ค่าที่ใกล้ 1 ที่สุดแต่ยังไม่ถึง
_ALMOST_ZERO = math.nextafter(0.0, 1.0)

# ---------------------------------------------------------------- ฟังก์ชันพื้นฐาน


def logistic(z: float) -> float:
    """σ(z) = 1/(1+e^-z) — อยู่ในช่วง (0,1) เสมอโดยไม่ต้อง clamp

    เขียนแยกสองกิ่งเพื่อกัน overflow ตอน z ติดลบมากๆ (e^|z| ระเบิดที่ราว z=-710)
    """
    if z >= 0.0:
        v = 1.0 / (1.0 + math.exp(-z))
    else:
        e = math.exp(z)
        v = e / (1.0 + e)
    # ทางคณิตศาสตร์ σ อยู่ใน (0,1) เสมอ แต่ float ปัดเป็น 1.0 พอดีเมื่อ z เกินราว 37
    # ถ้าปล่อยไว้ `rng.random() < p` จะกลายเป็นจริงทุกครั้ง = **ความแน่นอน** โผล่เข้ามาในโลก
    # ที่กติกาของมันเองบอกว่าฟ้ามีตัวแปรเสมอ นี่ไม่ใช่ clamp เชิงพฤติกรรม (ไม่ได้ตัดที่ 0.95
    # แบบของเดิม) แต่คือการกันไม่ให้ความละเอียดของ float สร้างกฎที่สมการไม่ได้บอก
    return min(_ALMOST_ONE, max(_ALMOST_ZERO, v))


def logit(p: float) -> float:
    """ผกผันของ logistic — ใช้แปลง "โอกาสที่ตั้งใจไว้" ให้เป็นพลังงานตั้งต้น z"""
    p = min(1.0 - 1e-12, max(1e-12, float(p)))
    return math.log(p / (1.0 - p))


# ---------------------------------------------------------------- ข้ามกำแพงพลังงาน


def barrier_odds(gap_ratio: float, shifts=(), base_p: float = 0.55,
                 softness: float = 0.5) -> float:
    """โอกาสข้ามกำแพง — ภาพของ Boltzmann: ระบบข้ามกำแพงพลังงานได้ตามพลังที่มีเทียบกับกำแพง

    `gap_ratio` คือส่วนเกิน **เทียบกับกำแพง** = (พลังที่สะสม - เกณฑ์)/เกณฑ์ ที่ต้องเป็น
    สัดส่วนไม่ใช่ค่าสัมบูรณ์ เพราะกำแพงขั้นที่ 25 สูงกว่าขั้นที่ 2 หลายเท่า การได้มาเกิน
    1 หน่วยจึงมีความหมายต่างกันคนละเรื่อง — ของเดิมใช้ค่าสัมบูรณ์ (`SURPLUS_BONUS` ต่อหนึ่ง
    หน่วย) จึงทำให้คนขั้นต่ำที่สะสมเกินนิดเดียวได้โบนัสเท่ากับคนขั้นสูงที่สะสมเกินมหาศาล

    `shifts` คือแรงอื่นๆ ที่ "ดันกำแพงขึ้นหรือกดลง" — ยา ความเสื่อม ความพร่องของฟ้าดิน
    ทั้งหมดบวกกันอยู่ใน **เลขชี้กำลัง** ไม่ใช่คูณกับความน่าจะเป็น นี่คือจุดที่ clamp หายไป:
    บวกกันเท่าไรผลลัพธ์ก็ยังอยู่ใน (0,1) เสมอ และไม่มีทางที่ตัวบีบจะกลายเป็นตัวตัดสินผล

    `softness` บอกว่ากำแพง "ชัน" แค่ไหน — 0.5 แปลว่าสะสมเกินครึ่งหนึ่งของเกณฑ์
    ดัน z ขึ้นหนึ่งหน่วย (โอกาส 0.55 -> 0.77) สะสมเป็นสองเท่าของเกณฑ์ -> 0.90
    """
    z = logit(base_p) + float(gap_ratio) / max(1e-6, softness)
    for s in shifts:
        z += float(s)
    return logistic(z)


# ---------------------------------------------------------------- จุดเหมาะสมด้วยอนุพันธ์


def best_wait_days(p_now: float, z_rate: float, life_left: float,
                   horizon: float = None) -> float:
    """ควรรออีกกี่วันก่อนลงมือ — หาจุดที่อนุพันธ์เป็นศูนย์

    โจทย์: ยิ่งรอ ยิ่งสะสม ยิ่งมีโอกาสสำเร็จ แต่ชีวิตที่เหลือไว้ใช้ผลนั้นก็สั้นลงทุกวัน
    ค่าที่อยากได้สูงสุดคือ f(t) = p(t)·(L - t) เมื่อ p(t) = σ(z₀ + k·t)

        f'(t) = k·σ'(t)·(L-t) - σ(t)  และ σ' = σ(1-σ)
        f'(t) = σ(t)·[ k·(1-σ(t))·(L-t) - 1 ]

    σ(t) > 0 เสมอ เงื่อนไขจุดเหมาะสมจึงเหลือแค่

        k·(1 - p(t))·(L - t) = 1

    อ่านเป็นภาษาคนได้ตรงตัว: **"วันที่เสียไปหนึ่งวัน ต้องซื้อโอกาสกลับมาให้คุ้มกับชีวิต
    ที่เหลือ ไม่งั้นรอไปก็ขาดทุน"** ฝั่งซ้ายลดลงเสมอเมื่อ t เพิ่ม (โอกาสเข้าใกล้ 1 และชีวิต
    ที่เหลือสั้นลง) รากจึงมีค่าเดียว หาได้ด้วยการแบ่งครึ่งไม่กี่รอบ

    พฤติกรรมที่โผล่ออกมาเองจากสมการนี้ โดยไม่ต้องเขียนกฎ "ถ้าแก่แล้วให้ใจร้อน"
      · คนหนุ่ม L ใหญ่   -> ฝั่งซ้ายมาก -> ควรรอสะสมต่อ
      · คนแก่ L เหลือน้อย -> ฝั่งซ้ายน้อย -> ควรลองทั้งที่โอกาสยังไม่ดี
      · คนที่สะสมช้า k เล็ก -> รอไปก็ไม่ได้อะไร -> ลงมือเลย
      · คนที่โอกาสดีอยู่แล้ว (1-p) เล็ก -> รอไปก็เพิ่มได้อีกนิดเดียว -> ลงมือเลย

    คืนจำนวนวันที่ควรรอ (0 = ลงมือได้เลย)
    """
    L = max(0.0, float(life_left))
    if L <= 0.0:
        return 0.0
    if horizon is None:
        horizon = L
    hi = max(0.0, min(float(horizon), L))
    k = float(z_rate)
    if k <= 0.0:
        return 0.0          # รอไปก็ไม่ดีขึ้น (หรือแย่ลง เพราะความเสื่อมชนะการสะสม)

    z0 = logit(min(1.0 - 1e-9, max(1e-9, p_now)))

    def margin(t):
        p = logistic(z0 + k * t)
        return k * (1.0 - p) * (L - t) - 1.0

    if margin(0.0) <= 0.0:
        return 0.0          # ผลได้จากการรอ ต่ำกว่าราคาของเวลาตั้งแต่วันแรก
    if margin(hi) > 0.0:
        return hi           # ยังคุ้มที่จะรอไปจนสุดขอบที่ยอมให้มอง

    lo = 0.0
    for _ in range(40):     # แบ่งครึ่ง 40 รอบ = ละเอียดกว่าหนึ่งวันเสมอในช่วงอายุขัยจริง
        mid = 0.5 * (lo + hi)
        if margin(mid) > 0.0:
            lo = mid
        else:
            hi = mid
    return 0.5 * (lo + hi)


# ---------------------------------------------------------------- การเติบโตแบบลอจิสติก


def logistic_growth(now: float, cap: float, rate_per_day: float, days: float) -> float:
    """พลังฟ้าดินฟื้นตัว — คำตอบแม่นตรงของ dH/dt = r·H·(1 - H/K)

        H(t) = K·H₀·e^{rt} / (K + H₀(e^{rt} - 1))

    ทำไมลอจิสติกถึงเหมาะกับ "พลังฟ้าดิน" มากกว่าการเติมเป็นเส้นตรงแล้วตัดที่เพดาน
      · โลกที่ถูกดูดจนแห้งฟื้นช้ามาก (H เล็ก -> r·H เล็ก) = ยุคเสื่อมที่ยาวนานจริงๆ
        ไม่ใช่ยุคเสื่อมที่หายไปเองภายในไม่กี่ปีเพราะการเติมคงที่
      · ช่วงกลางฟื้นเร็วที่สุด = ยุคฟื้นฟูที่คนรุ่นนั้นได้เปรียบ
      · เข้าใกล้เพดานแล้วช้าลงเอง **ไม่ต้องมี min() ไปตัด** การตัดที่เพดานคือการทำพลังงาน
        หายจากระบบเงียบๆ ซึ่งขัดกับกฎอนุรักษ์ที่โลกนี้ประกาศไว้เอง

    ใช้คำตอบแม่นตรงแทนการเดินทีละก้าว เพราะช่องว่างระหว่างเหตุการณ์ยาวได้เป็นหลักปี
    ถ้าเดินแบบออยเลอร์ก้าวเดียวจะพุ่งเกินเพดานทันที
    """
    K = float(cap)
    H0 = float(now)
    if K <= 0.0:
        return 0.0
    H0 = min(K, max(0.0, H0))
    rt = float(rate_per_day) * float(days)
    if rt <= 0.0 or H0 <= 0.0:
        return H0
    if rt > 60.0:            # e^60 ล้นความละเอียดแล้ว และแปลว่าอิ่มตัวไปนานแล้ว
        return K
    e = math.exp(rt)
    return K * H0 * e / (K + H0 * (e - 1.0))


# ---------------------------------------------------------------- กฎกำลังสองของแลนเชสเตอร์


def lanchester(power_a: float, power_b: float):
    """สงครามระหว่างหมู่คน — คืน (ฝ่ายที่ชนะ: 1 หรือ -1, สัดส่วนกำลังที่ฝ่ายชนะเหลือ)

    กฎกำลังสอง (F. W. Lanchester, 1916) สำหรับการรบที่ทุกคนยิงใส่กันได้พร้อมกัน

        dA/dt = -β·B ,  dB/dt = -α·A   =>   α·A² - β·B² = ค่าคงที่

    เมื่อฝ่ายอ่อนกว่าหมดกำลัง ฝ่ายที่เหลือจะเหลือกำลัง

        A_end = √(A₀² - B₀²)

    ทำไมถึงสำคัญกับโลกนี้: ของเดิมตัดสินด้วย `power_a >= power_b` แล้วให้ฝ่ายแพ้ตาย 30%
    ต่อคน ส่วนฝ่ายชนะ **ไม่เสียใครเลย** แปลว่าสงคราม 100 ต่อ 99 กับ 100 ต่อ 1 จบเหมือนกัน
    เป๊ะ ทั้งที่อย่างแรกควรเป็นชัยชนะที่เลือดอาบจนแทบไม่เหลือสำนัก

    กฎกำลังสองให้สิ่งนั้นมาฟรีๆ: ชนะฉิวเฉียด (99/100) เหลือกำลังแค่ 14% ส่วนชนะขาด
    (1/100) เหลือ 99.995% — และเลข 30% ที่ตั้งเอาเองก็ไม่ต้องมีอีกต่อไป
    """
    a = max(0.0, float(power_a))
    b = max(0.0, float(power_b))
    if a <= 0.0 and b <= 0.0:
        return 0, 0.0
    if a >= b:
        left = math.sqrt(max(0.0, a * a - b * b))
        return 1, (left / a if a > 0 else 0.0)
    left = math.sqrt(max(0.0, b * b - a * a))
    return -1, (left / b if b > 0 else 0.0)


# ---------------------------------------------------------------- เอนโทรปีกับทัณฑ์สวรรค์


def entropy_karma(lifespan: float, mortal_lifespan: float, k: float) -> float:
    """หนี้เอนโทรปีที่ผู้บำเพ็ญติดฟ้าดินไว้ — จากกฎข้อสองของอุณหพลศาสตร์

    ทุกระบบมีแนวโน้มไร้ระเบียบขึ้นตามเวลา การฝึกตนเพื่อยืดอายุคือการ **กดเอนโทรปีในตัวเอง
    ให้ต่ำกว่าที่ธรรมชาติกำหนด** ซึ่งทำได้ก็ต่อเมื่อผลักความไร้ระเบียบนั้นออกไปที่อื่น
    ฟ้าดินจึงต้องทวงคืน และการทวงคืนนั้นคือทัณฑ์สวรรค์

    ใช้ `ln` เพราะการชะลอวัยเป็นเรื่องของ **อัตราส่วน** ไม่ใช่ผลต่าง — คนที่อายุยืนเป็น
    สิบเท่าของสามัญชนติดหนี้เท่ากับคนที่อายุยืนเป็นร้อยเท่าของคนสิบเท่านั้น ln ทำให้การคูณ
    กลายเป็นการบวก ซึ่งตรงกับวิธีที่เอนโทรปีสะสมจริงๆ

    เป็นศูนย์สำหรับสามัญชน (ไม่ได้ฝืนอะไร ก็ไม่ติดหนี้อะไร)
    """
    base = max(1e-6, float(mortal_lifespan))
    ratio = max(1.0, float(lifespan) / base)
    return float(k) * math.log(ratio)


def strike_chance(karma: float, realm_level: float, lam: float) -> float:
    """โอกาสที่ฟ้าจะทวงหนี้ — CDF ของการแจกแจงเลขชี้กำลัง 1 - e^{-λ·karma·realm}

    รูปแบบนี้ถูกโดยธรรมชาติสำหรับ "เหตุการณ์ที่รอมานานแล้วต้องเกิด": อยู่ใน [0,1) เสมอ
    ไม่ต้อง clamp เข้าใกล้ 1 เมื่อหนี้สะสมมากขึ้น และที่หนี้เป็นศูนย์ก็ให้ศูนย์พอดี
    """
    x = max(0.0, float(karma)) * max(0.0, float(realm_level))
    if x <= 0.0:
        return 0.0
    return 1.0 - math.exp(-float(lam) * x)


# ---------------------------------------------------------------- ถ้ำกาลเวลา


def time_dilation(qi_density: float, critical_qi: float, cap: float = 12.0) -> float:
    """ปราณยิ่งหนาแน่น เวลาที่ผู้บำเพ็ญ "ได้ใช้" ยิ่งมากกว่าเวลาโลกภายนอก

    ที่มาเชิงฟิสิกส์คือการยืดของเวลาในสนามโน้มถ่วง โดยแทน "มวล" ด้วย "ความหนาแน่นปราณ"

        γ = 1 / √(1 - ρ/ρ_crit)

    **หมายเหตุเรื่องทิศของสูตร** — ตำราจะเขียน t_ใน = t_นอก·√(1-ρ/ρc) ซึ่งแปลว่าเวลา
    ข้างใน **เดินน้อยกว่า** ข้างนอก ถ้าเอามาใช้ตรงๆ ถ้ำที่ปราณเข้มที่สุดจะกลายเป็นถ้ำที่
    บำเพ็ญได้ **น้อยที่สุด** ซึ่งตรงข้ามกับที่ต้องการ (และขัดกับตัวอย่างในตำราเองที่บอกว่า
    "นั่งฝึกได้ตบะมหาศาลในพริบตา") สิ่งที่เราต้องการคือกรอบเวลาของผู้บำเพ็ญเทียบกับโลก
    ภายนอก ซึ่งเป็น **ส่วนกลับ** ของค่านั้น จึงใช้ γ = 1/√(...) ตามที่เขียนไว้ข้างบน

    ρ เข้าใกล้ ρ_crit เมื่อไร γ พุ่งเข้าอนันต์ = มิติทนไม่ไหวและพังทลาย เพดาน `cap` จึงไม่ใช่
    แค่กันตัวเลขระเบิด แต่คือ "เส้นที่ฟ้าดินยอมให้ได้" — ถ้ำที่ดีที่สุดคือถ้ำที่เกือบพัง
    """
    rc = max(1e-9, float(critical_qi))
    x = min(0.999999, max(0.0, float(qi_density) / rc))
    return min(float(cap), 1.0 / math.sqrt(1.0 - x))


def wave_sum(a1: float, a2: float, phase_deg: float) -> float:
    """รวมคลื่นสองลูก — A = √(A₁² + A₂² + 2A₁A₂cosΔθ)

    **ใช้ได้เฉพาะตอนสองฝ่ายออกแรงไปทางเดียวกัน** (ประสานวิชา) ไม่ใช่ตอนปะทะกัน
    ถ้าเอาไปใช้กับการโจมตีแล้วหักด้วยพลังฝ่ายรับ จะได้ผลกลับหัว: ธาตุเดียวกันทำให้
    โล่ของฝ่ายรับ "บวกเข้า" กับพลังโจมตี แปลว่าใช้ธาตุเดียวกับคู่ต่อสู้แล้วเจ็บหนักขึ้น
    การหักล้างของฝ่ายรับต้องใช้ `wave_cancel()` ข้างล่างแทน

    ยังไม่ถูกเรียกใช้ที่ไหนในเอนจิน เพราะตัวละครยังไม่มี "ธาตุ" เป็นข้อมูลจริง (ธาตุโผล่
    เฉพาะในคำบรรยายวิชา) เก็บไว้พร้อมใช้เมื่อไรที่เพิ่มระบบห้าธาตุให้ตัวละคร
    """
    th = math.radians(float(phase_deg))
    inner = a1 * a1 + a2 * a2 + 2.0 * a1 * a2 * math.cos(th)
    return math.sqrt(max(0.0, inner))


def wave_cancel(attack: float, defense: float, phase_deg: float) -> float:
    """พลังโจมตีที่เหลือหลังถูกฝ่ายรับหักล้าง — ส่วนที่อยู่ตรงข้ามเฟสเท่านั้นที่หักล้างได้

        หักล้างได้ = A_รับ · max(0, -cosΔθ)   ->  180° หักล้างเต็ม · 90° ไม่หักล้าง · 0° ไม่หักล้าง

    ตรงกับภาพ noise cancellation จริงๆ: คลื่นจะกลบกันได้ก็ต่อเมื่ออยู่ตรงข้ามเฟส
    ธาตุน้ำ (180° จากไฟ) จึงกลบไฟได้เต็ม ส่วนไฟปะทะไฟ (0°) กลบกันไม่ได้เลย
    """
    th = math.radians(float(phase_deg))
    cancelled = max(0.0, -math.cos(th)) * max(0.0, float(defense))
    return max(0.0, float(attack) - cancelled)


# ---------------------------------------------------------------- กฎกำลังของการฝึกฝน


def practice_mastery(reps: float, exponent: float) -> float:
    """ความชำนาญหลังฝึกไปแล้วกี่ครั้ง — กฎกำลังของการฝึกฝน (Power Law of Practice)

        M(n) = 1 - (1 + n)^(-b)

    กฎนี้วัดได้จริงในมนุษย์ตั้งแต่งานของ Snoddy (1926) จนถึง Newell & Rosenbloom (1981)
    เวลาที่ใช้ต่อครั้งลดลงตามกำลังของจำนวนครั้ง ไม่ใช่ลดลงแบบเลขชี้กำลัง แปลว่า
    **ความก้าวหน้าช้าลงเรื่อยๆ แต่ไม่เคยหยุด** ซึ่งเป็นรูปที่ถูกสำหรับการฝึกวิชา

    ทำไมโลกนี้ต้องมี: วิชาเคยเป็น binary — มีหรือไม่มี ฝึกวิชาที่มีอยู่แล้วจึงไม่ได้อะไรเลย
    ต้องไปหาวิชาใหม่ท่าเดียว วัดจริงโลก 50 ปี: วิชาต่อคนเฉลี่ย **0.95** และ **1,020 จาก
    2,184 คนไม่มีวิชาเลยสักอัน** (47%) ในโลกบำเพ็ญ
    ผลที่ตามมาเมื่อมีความชำนาญ: คนที่มีวิชาเดียวแต่ฝึกมาสี่สิบปี เหนือกว่าคนที่มีสิบวิชา
    แบบงูๆ ปลาๆ ได้ — ซึ่งเป็นแก่นของแนวนี้ และอธิบายว่าทำไมผู้เฒ่าถึงน่ากลัว
    """
    n = max(0.0, float(reps))
    b = max(1e-6, float(exponent))
    return 1.0 - (1.0 + n) ** (-b)


def practice_gain(reps: float, exponent: float) -> float:
    """ได้ความชำนาญเพิ่มเท่าไรจากการฝึก "ครั้งถัดไป" — ส่วนต่างของกฎข้างบน

    ครั้งแรกได้เยอะ ครั้งที่ห้าสิบได้นิดเดียว แต่ไม่เคยเป็นศูนย์
    """
    return practice_mastery(reps + 1.0, exponent) - practice_mastery(reps, exponent)


# ---------------------------------------------------------------- ปริมาณสารสนเทศ


def surprisal(p: float) -> float:
    """ความประหลาดใจของเหตุการณ์ที่มีโอกาส p — วัดเป็นบิต (Shannon, 1948)

        I = -log2(p)

    โอกาส 50% = 1 บิต · 2% = 5.6 บิต · 0.1% = 10 บิต
    สิ่งที่เกิดตามคาดแทบไม่มีค่าสารสนเทศเลย (โอกาส 90% = 0.15 บิต)

    ทำไมโลกนี้ต้องมี: เป้าหมายของเอนจินคือบันทึกที่เอาไปเขียนเป็นนิยายได้ แต่หน้าอ่าน
    ตัดตอนด้วย "ช่วงเวลารายปี" ซึ่งเป็นเกณฑ์เชิงเวลา ไม่ใช่เชิงเรื่อง เอนจินรู้ความน่าจะเป็น
    ของทุกอย่างอยู่แล้ว (โอกาสข้ามขั้น โอกาสฝึกสำเร็จ โอกาสชนะ) การเก็บ -log2(p) ไว้กับ
    เหตุการณ์จึงทำให้ **"เขาข้ามขั้นสำเร็จตามคาด" แยกออกจาก "เขาข้ามขั้นสำเร็จทั้งที่
    โอกาส 4%" ได้ด้วยตัวเลข** ไม่ต้องให้คนมานั่งอ่านแล้วเดาเอง
    """
    q = min(1.0, max(1e-12, float(p)))
    return -math.log2(q)


# ---------------------------------------------------------------- กระบวนการฮอว์กส์


def hawkes_intensity(base: float, marks, now: float, alpha: float, decay_days: float) -> float:
    """อัตราการเกิดเหตุ ณ เวลาหนึ่ง เมื่อเหตุก่อนหน้าจุดชนวนเหตุถัดไป (Hawkes, 1971)

        λ(t) = μ + Σ α·e^{-(t - tᵢ)/τ}

    `marks` คือรายการเวลาที่เคยเกิดเหตุ (วัน) แต่ละครั้งดันอัตราขึ้น α แล้วสลายด้วยครึ่งชีวิต

    ทำไมโลกนี้ต้องมี: วัดจริงโลก 50 ปี — ล้างแค้นกับลอบสังหารรวม 2,436 ครั้ง สัมประสิทธิ์
    การกระจาย (sd/mean ของช่องว่างระหว่างเหตุ) = **1.10** ซึ่งเท่ากับปัวซองพอดี แปลว่า
    **ความรุนแรงในโลกนี้เกิดแบบสุ่มล้วน ไม่เกาะกลุ่มเลย** ความรุนแรงจริงไม่เป็นแบบนั้น —
    มันจุดชนวนตัวเอง ฆ่าหนึ่งครั้งแล้วแถบนั้นเดือดต่ออีกหลายปี
    ผลที่ได้คือ "ยุคนองเลือด" โผล่ออกมาเอง แทนที่จะต้องประกาศว่าเป็นยุคอะไร
    """
    lam = max(0.0, float(base))
    tau = max(1e-6, float(decay_days)) / math.log(2.0)   # ครึ่งชีวิต -> ค่าคงที่เวลา
    for t in (marks or ()):
        dt = float(now) - float(t)
        if dt < 0:
            continue
        if dt / tau > 60.0:
            continue                                     # สลายจนหมดแล้ว
        lam += float(alpha) * math.exp(-dt / tau)
    return lam


# ---------------------------------------------------------------- ทฤษฎีการประมูล


def second_price(bids) -> tuple:
    """ประมูลแบบวิกเครย์ — คืน (ดัชนีผู้ชนะ, ราคาที่จ่ายจริง)

    ผู้ชนะคือคนที่ให้ราคาสูงสุด แต่ **จ่ายเท่าราคาอันดับสอง** ผลที่ Vickrey (1961) พิสูจน์ไว้
    คือกลยุทธ์ที่ดีที่สุดของทุกคนกลายเป็นการเสนอมูลค่าจริงในใจตัวเอง ไม่ต้องเดาใจคนอื่น
    ซึ่งทำให้ราคาปิดสะท้อน "ของชิ้นนี้มีค่าแค่ไหนสำหรับคนอันดับสอง" — คือราคาตลาดจริงๆ

    ทำไมโลกนี้ต้องมี: วัดจริงโลก 50 ปี — `ชนะประมูล 351 · พลาดประมูล 351 · ประมูล 351`
    **เท่ากันเป๊ะทั้งสามตัว** แปลว่าทุกงานประมูลมีผู้เข้าร่วมสองคนพอดีเสมอ ซึ่งไม่ใช่งานประมูล
    """
    vals = list(bids or ())
    if not vals:
        return -1, 0.0
    if len(vals) == 1:
        return 0, float(vals[0])
    order = sorted(range(len(vals)), key=lambda i: (-float(vals[i]), i))
    return order[0], float(vals[order[1]])


def lognormal_value(base: float, sigma: float, u: float) -> float:
    """มูลค่าที่มี "หางหนัก" — ส่วนใหญ่เล็ก นานๆ ครั้งเปลี่ยนชีวิต

        v = base · e^{σ·z}   เมื่อ z คือค่ามาตรฐานปกติที่ได้จาก u ∈ (0,1)

    ใช้ล็อกนอร์มัลเพราะมูลค่าของสิ่งของในโลกจริงเกิดจากปัจจัยหลายอย่าง **คูณกัน**
    (คุณภาพ x ความหายาก x สภาพ x วาสนาของผู้พบ) ผลคูณของตัวแปรสุ่มหลายตัวลู่เข้าหา
    ล็อกนอร์มัลเสมอ ต่างจากผลบวกที่ลู่เข้าหาการแจกแจงปกติ

    `u` คือเลขสุ่ม 0-1 ที่ผู้เรียกดึงมาเอง (ฟังก์ชันนี้ยังไม่แตะ rng) แปลงเป็น z ด้วยสูตร
    ประมาณของ Beasley-Springer-Moro แบบย่อ ซึ่งแม่นพอสำหรับงานนี้และไม่ต้องพึ่งไลบรารี
    """
    u = min(1.0 - 1e-9, max(1e-9, float(u)))
    # ผกผันของ CDF ปกติแบบประมาณ (Acklam/BSM ย่อ) — พอสำหรับช่วงกลาง และปลอดภัยที่ปลาย
    if u < 0.5:
        t = math.sqrt(-2.0 * math.log(u))
        z = -(t - (2.515517 + 0.802853 * t + 0.010328 * t * t)
              / (1.0 + 1.432788 * t + 0.189269 * t * t + 0.001308 * t ** 3))
    else:
        t = math.sqrt(-2.0 * math.log(1.0 - u))
        z = (t - (2.515517 + 0.802853 * t + 0.010328 * t * t)
             / (1.0 + 1.432788 * t + 0.189269 * t * t + 0.001308 * t ** 3))
    return max(0.0, float(base)) * math.exp(float(sigma) * z)


# ---------------------------------------------------------------- อุปสงค์อุปทาน


def scarcity_price(base: float, demand: float, supply: float,
                   elasticity: float, lo: float = 0.15, hi: float = 12.0) -> float:
    """ราคาตามความขาดแคลน — P = P₀·(D/S)^ε

    ε คือความยืดหยุ่น: ε=1 คือราคาแปรผันตรงกับอัตราส่วน ε<1 คือของจำเป็นที่คนยังต้องซื้อ
    แม้ราคาพุ่ง (ยา วัตถุดิบบำเพ็ญ) ใช้กำลังแทนการคูณเชิงเส้นเพราะ **สัดส่วน** คือสิ่งที่
    มีความหมาย ไม่ใช่ผลต่าง — ของที่เหลือครึ่งเดียวควรแพงขึ้นเท่ากันไม่ว่าจะเริ่มจาก 100
    หรือ 10,000 ชิ้น

    ทำไมโลกนี้ต้องมี: วัดจริงโลก 50 ปี — `ค้าขาย` 3,453 ครั้ง **ได้ผลลัพธ์เดียวกันหมด**
    คือคำว่า "ค้าขาย" ไม่มีราคา ไม่มีกำไรขาดทุน ไม่มีอะไรให้ตัดสินใจ ทั้งที่เอนจินมีข้อมูล
    ครบแล้ว (`eco_ratio` คืออุปทาน `wants` คืออุปสงค์) แค่ยังไม่มีใครเอามาคูณกัน
    """
    d = max(1e-6, float(demand))
    s = max(1e-6, float(supply))
    mult = (d / s) ** float(elasticity)
    return max(0.0, float(base)) * min(float(hi), max(float(lo), mult))


# ---------------------------------------------------------------- อันดับแบบ Elo


def elo_expected(rating_a: float, rating_b: float, spread: float = 400.0) -> float:
    """โอกาสที่ a จะชนะ b ตามคะแนนที่มี — ต่างกัน 400 แต้ม = ชนะ 10 ต่อ 1"""
    return 1.0 / (1.0 + 10.0 ** ((float(rating_b) - float(rating_a)) / float(spread)))


def elo_update(rating_a: float, rating_b: float, a_won: bool,
               k: float = 24.0, spread: float = 400.0) -> tuple:
    """คะแนนใหม่ของทั้งคู่หลังปะทะ (Elo, 1960) — คืน (a ใหม่, b ใหม่)

    คุณสมบัติที่ทำให้มันเหมาะกับกระดานจัดอันดับยุทธภพ
      · ชนะคนที่อันดับต่ำกว่ามาก แทบไม่ได้แต้ม — ไล่รังแกคนอ่อนไม่ทำให้ไต่อันดับได้
      · แพ้คนที่อันดับต่ำกว่ามาก เสียแต้มหนัก — "ม้ามืดโค่นเซียน" สะเทือนกระดานจริง
      · ผลรวมแต้มคงที่ ไม่เฟ้อ

    ทำไมโลกนี้ต้องมี: 排行榜 เป็นของคู่แนวนี้ และตอนนี้ `merit` เป็นแค่ตัวนับที่เพิ่มขึ้น
    อย่างเดียว ทำนายอะไรไม่ได้เลย Elo ให้ชื่อเสียงที่ **วัดได้และทำนายผลการปะทะได้จริง**
    และให้เป้าหมายชีวิตแบบใหม่กับตัวละครที่ไม่ได้สนใจการไต่ขั้น
    """
    exp_a = elo_expected(rating_a, rating_b, spread)
    s = 1.0 if a_won else 0.0
    delta = float(k) * (s - exp_a)
    return rating_a + delta, rating_b - delta


# ---------------------------------------------------------------- การแพร่บนกราฟ


def spread_reach(steps: int, per_step: float) -> float:
    """โอกาสที่ข่าวจะเดินทางถึงที่ที่อยู่ห่างออกไปกี่ก้าวบนกราฟ

        P = p_ก้าว ^ ก้าว

    ทำไมใช้ "จำนวนก้าวบนกราฟ" ไม่ใช่ระยะทางแบบยุคลิด: โลกนี้ไม่มีพิกัด มันเป็นกราฟของ
    สถานที่ที่เชื่อมกันด้วยเส้นทาง (ดู places.py) ระยะที่มีความหมายจริงจึงเป็นจำนวนต่อที่
    ต้องเดินทาง — กฎกำลังสองผกผันใช้ไม่ได้เพราะไม่มีปริมาตรให้กระจาย แต่การลดทอนต่อก้าว
    (เหมือนการดูดกลืนของคลื่นในตัวกลาง) ใช้ได้ตรงไปตรงมา

    ผลคือ **วีรกรรมในหุบเขาห่างไกลใช้เวลาและโอกาสกว่าจะถึงเมืองหลวง** และเมืองที่เป็น
    ชุมทาง (ต่อได้หลายทาง) กลายเป็นศูนย์กลางข่าวสารโดยธรรมชาติ ไม่ต้องประกาศว่าเป็น
    """
    n = max(0, int(steps))
    if n == 0:
        return 1.0
    p = min(1.0, max(0.0, float(per_step)))
    return p ** n


# ---------------------------------------------------------------- การเก็บเกี่ยวทรัพยากรหมุนเวียน
# แบบจำลองของ Schaefer (1954) ที่ใช้กำหนดโควตาจับปลาทั่วโลกจริงๆ
#
#     dH/dt = r·H·(1 - H/K) - E
#
# ต่างจาก logistic_growth ข้างบนแค่พจน์ -E แต่พจน์เดียวนั้นเปลี่ยนโลกทั้งใบ เพราะมันพา
# ผลลัพธ์ที่พิสูจน์แล้วทางคณิตศาสตร์มาด้วยสองข้อ
#
#   1. ผลผลิตยั่งยืนสูงสุด (MSY) อยู่ที่ H = K/2 พอดี ได้ผลผลิต rK/4
#      แปลว่าโลกนี้ "ให้ปราณได้มากที่สุดตอนคลังเหลือครึ่งเดียว" ไม่ใช่ตอนเต็ม
#   2. ถ้าการเก็บเกี่ยวรวมเกิน rK/4 **ไม่มีจุดสมดุลเหลืออยู่เลย** คลังจะไหลลงศูนย์เสมอ
#      ไม่ว่าจะเริ่มจากเต็มแค่ไหน — นี่คือ "ยุคเสื่อม" ที่ไม่ต้องเขียนเป็นเหตุการณ์
#
# และมีกับดักที่ต้องรู้: ที่ H = 0 พจน์การเติบโตเป็นศูนย์ **โลกที่ถูกดูดจนแห้งสนิทจะไม่มี
# วันฟื้นเองตลอดกาล** รันตรวจแล้วเจอจริง — โลกตายที่ปีที่ 120 แล้วค้างที่ศูนย์ถึงปีที่ 800
# ทางออกคือพจน์เมล็ดจากภายนอก (ปุถุชนเติมพลังให้โลกทุกปี ดู config.LIFE_INFLOW)
# ซึ่งทำให้ศูนย์ไม่ใช่กับดักถาวร และเป็นตัวที่เปลี่ยน "โลกตาย" ให้กลายเป็น "วัฏจักรของยุค"

def harvest_step(now: float, cap: float, rate_per_day: float,
                 harvest: float, seed: float, days: float) -> float:
    """เดินคลังทรัพยากรไปข้างหน้าหนึ่งช่วง ด้วยการเติบโตลอจิสติกลบการเก็บเกี่ยว

    ใช้ออยเลอร์แบบชัดแจ้งแทนสูตรปิด เพราะสมการนี้ไม่มีคำตอบปิดเมื่อมี E และเพราะช่วงเวลา
    ที่ซิมเรียกจริงสั้นพอ (หลักวันถึงหลักปี) ที่ความคลาดเคลื่อนจะเล็กกว่าความหยาบของ
    ตัวเลขที่ป้อนเข้ามาเองอยู่แล้ว — แบ่งเป็นก้าวย่อยไม่ให้ก้าวเดียวข้ามยอดของเส้นโค้ง

    คืนคลังใหม่ ไม่เคยติดลบ และไม่เคยเกินเพดาน แต่**ส่วนที่เกินไม่ได้หายไปเฉยๆ**
    ผู้เรียกต้องหักการเก็บเกี่ยวจากผู้เก็บเกี่ยวเองด้วย ไม่งั้นก็กลับไปเป็น min() แบบเดิม
    """
    H = max(0.0, float(now))
    K = max(1e-9, float(cap))
    r = max(0.0, float(rate_per_day))
    E = max(0.0, float(harvest))
    d = max(0.0, float(days))
    if d <= 0.0:
        return H
    steps = max(1, min(64, int(d / 30.0) + 1))
    dt = d / steps
    per_day_seed = max(0.0, float(seed))
    for _ in range(steps):
        growth = r * H * (1.0 - H / K)
        H += (growth + per_day_seed - E) * dt
        if H <= 0.0:
            H = 0.0
        elif H > K:
            H = K
    return H


def max_sustainable_yield(rate_per_day: float, cap: float) -> float:
    """ผลผลิตยั่งยืนสูงสุดต่อวัน = rK/4 — เกินเส้นนี้เมื่อไรคลังไหลลงศูนย์เสมอ"""
    return max(0.0, float(rate_per_day)) * max(0.0, float(cap)) / 4.0


# ---------------------------------------------------------------- การผ่อนคลายแบบเอกซ์โพเนนเชียล
def relax(now: float, target: float, rate_per_day: float, days: float) -> float:
    """เดินค่าหนึ่งเข้าหาเป้าหมายแบบเอกซ์โพเนนเชียล

        x(t) = x* + (x0 - x*)·e^{-λt}

    สมการเดียวกับการสลายตัวของกัมมันตรังสีและการเย็นตัวของนิวตัน เลือกใช้เพราะมัน
    **บอกความเร็วเป็นตัวเลขที่เขียนลงหน้าบันทึกได้** — ครึ่งชีวิต = ln2/λ ตั้ง λ ให้
    ครึ่งชีวิตเท่ากับแปดปี ก็แปลว่า "ทิ้งไว้แปดปี ตกครึ่งทางไปหาระดับที่เลี้ยงตัวได้"

    ต่างจากการนับตัวนับจนถึงเกณฑ์แล้วกระโดด (ของเดิม: decay >= REGRESS_AT แล้วขั้นหล่น
    ทีละหนึ่ง) ตรงที่มันต่อเนื่อง ย้อนกลับได้ และไม่มีเส้นวิเศษให้ตัวละครไปค้างอยู่ข้างๆ
    เป็นรูปแบบปิด ไม่ใช่ออยเลอร์ จึงไม่แกว่งแม้ช่วงเวลาที่ป้อนเข้ามาจะยาวมาก
    """
    lam = max(0.0, float(rate_per_day))
    d = max(0.0, float(days))
    if lam <= 0.0 or d <= 0.0:
        return float(now)
    keep = math.exp(-lam * d)
    return float(target) + (float(now) - float(target)) * keep


def half_life_days(rate_per_day: float) -> float:
    """แปลง λ เป็นครึ่งชีวิตเป็นวัน — มีไว้ให้คอมเมนต์และบันทึกพูดเป็นภาษาคนได้"""
    lam = max(1e-12, float(rate_per_day))
    return math.log(2.0) / lam


# ---------------------------------------------------------------- ฟังก์ชันผลิตแบบคอบบ์-ดักลาส
def cobb_douglas(scale: float, labour: float, land: float, alpha: float) -> float:
    """ผลผลิตจากปัจจัยสองอย่างที่ทดแทนกันไม่ได้

        Y = A · L^α · T^(1-α)

    ใช้กับผลผลิตของสำนัก: L = จำนวนศิษย์ · T = ปราณในอาณาเขตที่ครองอยู่
    เลือกอันนี้เพราะสองคุณสมบัติที่ตรงกับปัญหาที่วัดเจอ ไม่ใช่เพราะมันมีชื่อเสียง

      · **ผลตอบแทนลดน้อยถอยลงในแต่ละปัจจัย** (α < 1) — รับศิษย์เพิ่มเท่าตัวไม่ได้ผลผลิต
        เท่าตัว สำนักใหญ่จึงไม่โตไม่หยุด ซึ่งเป็นสิ่งที่ monthly_resource คงที่ทำไม่ได้เลย
      · **ปัจจัยหนึ่งเป็นศูนย์แล้วผลผลิตเป็นศูนย์** — ศิษย์พันคนบนแผ่นดินที่ปราณแห้ง
        ได้ศูนย์ อาณาเขตจึงมีค่าให้แย่งชิงจริง ไม่ใช่แค่ฉากหลังของการต่อสู้

    ผลรวมของเลขชี้กำลังเป็นหนึ่งพอดี = ผลตอบแทนต่อขนาดคงที่ ขยายทั้งศิษย์และอาณาเขต
    เป็นสองเท่าได้ผลผลิตสองเท่า ไม่ใช่สี่เท่า — กันสำนักที่ชนะสงครามครั้งเดียวแล้วโตพรวด
    """
    L = max(0.0, float(labour))
    T = max(0.0, float(land))
    if L <= 0.0 or T <= 0.0:
        return 0.0
    a = min(1.0, max(0.0, float(alpha)))
    return max(0.0, float(scale)) * (L ** a) * (T ** (1.0 - a))


# ---------------------------------------------------------------- ราคาของทรัพยากรที่มีจำกัด
def hotelling_price(base: float, reserve_frac: float, elasticity: float,
                    lo: float = 0.5, hi: float = 20.0) -> float:
    """ราคาของสิ่งที่ขุดแล้วหมดไป — ยิ่งเหลือน้อยยิ่งแพง ตั้งแต่ก่อนหมด

    กฎของ Hotelling (1931) ว่าราคาสุทธิของทรัพยากรที่ใช้แล้วหมดต้องโตด้วยอัตราคิดลด
    ไม่งั้นเจ้าของก็ควรขุดขายให้หมดวันนี้ดีกว่าเก็บไว้ เขียนในรูปที่ผูกกับปริมาณสำรองที่
    เหลือแทนเวลา เพราะโลกนี้ไม่มีตลาดล่วงหน้าให้คิดลด แต่มีคนที่มองเห็นว่าแหล่งกำลังจะแห้ง

        p = p₀ · (สำรองที่เหลือ)^(-ε)

    ต่างจาก scarcity_price ข้างบนตรงที่อันนั้นถามว่า "ตอนนี้ของขาดไหม" ส่วนอันนี้ถามว่า
    "ของกำลังจะหมดไหม" — สองคำถามคนละคำถาม และคำตอบที่สองคือสิ่งที่ทำให้ตัวละคร
    แย่งกันตุนตั้งแต่ยังมีของ แทนที่จะมารู้ตัวตอนหยิบแล้วไม่มี
    """
    frac = min(1.0, max(1e-4, float(reserve_frac)))
    p = max(0.0, float(base)) * (frac ** (-max(0.0, float(elasticity))))
    return min(max(0.0, float(base)) * hi, max(max(0.0, float(base)) * lo, p))
