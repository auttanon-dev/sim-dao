    if ch.rivals:
        bump = 14 if "พยาบาท" in ch.traits else 6
        # แค้นที่แพ้ซ้ำแล้วซ้ำอีกไม่ใช่เรื่องเล่า มันคือลูปค้าง — วัดจริงจากบันทึกปีที่ 129-152:
        # เหลียงไห่อวิ๋นบุกเจียงถิงเฉิน **8 ครั้งใน 3 ปี** จบด้วย "พ่ายแพ้" 5 ครั้ง และทุกครั้ง
        # ที่แพ้ apply_defeat ทำ lose.rivals[win] += 2 → ความแค้นโตขึ้น → น้ำหนักล้างแค้นสูงขึ้น
        # → บุกอีก เป็นป้อนกลับบวกล้วนที่ไม่มีทางออกนอกจากมีคนตาย
        #
        # ไม่ต้องเขียนกฎใหม่ให้โลก แค่ให้ตัวละครทำสิ่งที่คนจริงทำ: ประเมินก่อนว่า "ตอนนี้สู้ไหวไหม"
        # ระบบเก็บ Elo ของทุกคนจากทุกการปะทะอยู่แล้ว (rules.resolve_clash → physics.elo_update)
        # elo_expected จึงให้ "โอกาสชนะที่คาดไว้" ได้ฟรีโดยไม่ต้องจำลองการต่อสู้ล่วงหน้า
        # โอกาสต่ำ = ยังไม่ถึงเวลา เก็บแค้นไว้ก่อนแล้วไปสะสมกำลัง
        # และเพราะแพ้ครั้งที่สอง Elo ยิ่งตก โอกาสบุกครั้งที่สามจึงยิ่งต่ำลงเอง — ลูปปิดตัวเอง
        # เหลือพื้นไว้ (REVENGE_ODDS_FLOOR) เพราะ "รู้ว่าสู้ไม่ได้แต่ยังไป" คือสิ่งที่คนพยาบาททำ
        # ถ้าตัดเป็นศูนย์ ความแค้นจะกลายเป็นการคำนวณล้วนจนไม่เหลือความเป็นคน
        foe_cid = max(ch.rivals, key=lambda c: ch.rivals[c])
        foe = sim.cast[foe_cid] if 0 <= foe_cid < len(sim.cast) else None
        if foe is not None and foe.alive:
            odds = PHYS.elo_expected(getattr(ch, "elo", 1500.0),
                                     getattr(foe, "elo", 1500.0))
            ready = max(C.REVENGE_ODDS_FLOOR,
                        min(1.0, odds / C.REVENGE_ODDS_FAIR))
            # คูณทั้งก้อน ไม่ใช่แค่ส่วนที่บวกเพิ่ม — เพราะ "ล้างแค้น" ไม่มีความหมายเลยถ้าไม่มี
            # คู่แค้น น้ำหนักฐานจากตารางเหตุการณ์จึงอยู่ใต้เงื่อนไขเดียวกันทั้งหมด
            # วัดจริง: ถ้าคูณแค่ bump แพ้ติดกันหกครั้งน้ำหนักขยับจาก 34.0 เหลือ 31.8 (-6%)
            # ยังติดเมนูสิบสองตัวเลือกอยู่ทุกครั้ง ตัวเอกจึงบุกซ้ำต่อไปเหมือนเดิม — แก้ไม่ขึ้น
            w["ล้างแค้น"] = w.get("ล้างแค้น", 0) * ready
            bump *= ready
            if ready < 1.0:
                # ยังสู้ไม่ได้ — แค้นกลายเป็นแรงฝึก ไม่ใช่แรงบุก นี่คือจังหวะ "เก็บตัวสิบปี"
                hold = (1.0 - ready) * C.REVENGE_TRAIN_W
                w["ฝึกวิชา"] = w.get("ฝึกวิชา", 0) + hold
                w["บำเพ็ญ"] = w.get("บำเพ็ญ", 0) + hold * 0.6
        w["ล้างแค้น"] = w.get("ล้างแค้น", 0) + bump
    # วงจรแค้นแบบฮอว์กส์ — ความรุนแรงจุดชนวนตัวเอง แล้วสลายไปตามปี
    # วัดจริงก่อนมี: ล้างแค้น+ลอบสังหาร 2,436 ครั้งใน 50 ปี สัมประสิทธิ์การกระจาย 1.10
    # = เท่ากับปัวซองพอดี แปลว่าความรุนแรงเกิดแบบสุ่มล้วน ไม่เกาะกลุ่มเลย
    # ความรุนแรงจริงไม่เป็นแบบนั้น — ฆ่าหนึ่งครั้งแล้วแถบนั้นเดือดต่ออีกหลายปี
    _heat = sim.feud_heat(ch.place) if hasattr(sim, "feud_heat") else 0.0
    if _heat > 0.01:
        for _k in ("ล้างแค้น", "ลอบสังหาร", "ชิงสมบัติ", "ดักปล้น"):
            if _k in w and w[_k] > 0:
                w[_k] *= 1.0 + min(C.FEUD_HEAT_CAP, _heat)
        # และคนที่ไม่ได้อยากยุ่งก็หลบเข้าบ้านกันมากขึ้นในยุคที่เลือดนอง
        w["ซ่อนตัว"] = w.get("ซ่อนตัว", 0) + min(C.FEUD_HEAT_CAP, _heat) * C.FEUD_HIDE_W
    unresolved = sum(1 for d in ch.debts if not d["done"])
    if unresolved >= 3:
        w["สะสางเรื่องเก่า"] = w.get("สะสางเรื่องเก่า", 0) + 5 + unresolved
    if "โลภมาก" in ch.traits:
        w["ชิงสมบัติ"] = w.get("ชิงสมบัติ", 0) + 10
        w["ทรยศ"] = w.get("ทรยศ", 0) + 5
    if "ใจโอบอ้อม" in ch.traits:
        w["ถ่ายทอดวิชา"] = w.get("ถ่ายทอดวิชา", 0) + 8
        w["ให้สัญญา"] = w.get("ให้สัญญา", 0) + 6
        w["ทรยศ"] = w.get("ทรยศ", 0) * 0.2
    if ch.spy_for is not None and ch.org is not None:
        w["ไส้ศึกลงมือ"] = w.get("ไส้ศึกลงมือ", 0) + 12
    # สงครามสำนักต้องมี "สำนัก" ทั้งสองฝั่งถึงจะเกิดได้ — ปิดไว้ก่อนแล้วเปิดเฉพาะคนที่มีจริง
