# -*- coding: utf-8 -*-
"""หน่วยจริงของโลก — แปลง "หน่วยกราฟ" ของ geo.py เป็นกิโลเมตร และความเร็วเดินทางเป็น กม./วัน

ทำไมต้องมีไฟล์นี้
----------------
ระยะใน geo.EDGES ไม่มีหน่วย (travel.py เขียนไว้เองว่า "หน่วยกราฟไม่ใช่เมตร") ความเร็วเดิมคือ
3 หน่วย/วัน และผู้บำเพ็ญเร็วขึ้นแค่ 12% ต่อขั้น — ข้ามโลกมนุษย์ทั้งใบใช้ 66 วันเดินเท้า ถ้าคนเดิน
วันละ 30 กม. โลกทั้งใบจึงกว้างแค่ราว 2,000 กม. (ขนาดประเทศ ไม่ใช่ดาวเคราะห์)

โหมดดาวเคราะห์ (`config.REAL_DISTANCE = True`) ตีความแผนที่เดิมใหม่โดยไม่ต้องสร้าง geo.py ใหม่:
  * 1 หน่วยกราฟ = `KM_PER_UNIT` กม. (ค่าตั้ง 100) — แผนที่โลกมนุษย์กว้าง ~183 หน่วย = ~18,300 กม.
    ใกล้ครึ่งเส้นรอบวงของดาวขนาดโลก (20,015 กม.) คือแผนที่หนึ่งใบ = ซีกหนึ่งของดาว
  * ความเร็วคิดเป็น กม./วัน จริง: ปุถุชนเดินเท้า 30 กม./วัน แล้วโตแบบเรขาคณิตตามขั้น
    (เหาะเหิน) — ช่องว่างระหว่างคนธรรมดากับเซียนจึงเป็นหลักร้อยถึงหมื่นเท่า ไม่ใช่ 4 เท่า

ชื่อค่า: ใช้ `REAL_DISTANCE` เพราะ `config.PLANET_SCALE` มีอยู่แล้วและหมายถึงอย่างอื่น (ความถี่ของ
สนาม noise บนผิวดาวใน noise.py/terrain.py) ดาวของ noise นั้นมีรัศมีสัมพัทธ์ 1.0 "ไม่มีความหมายทาง
กายภาพ" และฉายแผนที่ 1,000 หน่วยเป็นมุม 45° — เป็นคนละเรื่องกับสเกล กม. ที่นี่ และยังไม่ได้ผูกเข้าหากัน

ข้อจำกัดที่ต้องรู้: แผนที่ยังเป็นระนาบ ระยะคือความยาวถนนในกราฟคูณสเกล ไม่ใช่ระยะวงกลมใหญ่บน
ทรงกลม ค่าตั้งคือ **ปิด** — เปิดแล้วเวลาเดินทางของปุถุชนยาวขึ้นราว 10 เท่า สมดุลโลกเปลี่ยนทั้งใบ
"""
import math

from . import config as C

EARTH_RADIUS_KM = 6371.0
EARTH_GRAVITY = 9.80665      # m/s^2

# ดาวของแต่ละชั้นโลก (World.tier) — รัศมีและแรงโน้มถ่วงที่ผิว
# โลกชั้นสูงใหญ่กว่าและหนักกว่า: ตรงกับกฎเดิม "โลกระดับสูงพลังบริสุทธิ์กว่าแต่อันตรายกว่า"
# ตัวเลขชั้น 1–2 เป็นค่าที่กำหนดขึ้นเพื่อเกม ไม่ใช่ดาวจริง ส่วนชั้น 0 คือค่าของโลกจริง
PLANET_BY_TIER = {
    0: {"radius_km": EARTH_RADIUS_KM, "gravity": EARTH_GRAVITY},
    1: {"radius_km": EARTH_RADIUS_KM * 3.0, "gravity": EARTH_GRAVITY * 1.5},
    2: {"radius_km": EARTH_RADIUS_KM * 10.0, "gravity": EARTH_GRAVITY * 2.5},
}


def planet_of(tier: int) -> dict:
    """ดาวของชั้นโลกนั้น พร้อมเส้นรอบวง — ชั้นที่ไม่รู้จักใช้ชั้นสูงสุดที่มี"""
    p = dict(PLANET_BY_TIER[min(max(0, int(tier)), max(PLANET_BY_TIER))])
    p["circumference_km"] = 2.0 * math.pi * p["radius_km"]
    return p


def km_per_unit(cfg=None) -> float:
    return float(getattr(cfg or C, "KM_PER_UNIT", 100.0))


def to_km(distance_units: float, cfg=None) -> float:
    """ระยะกราฟ -> กม. (ใช้ได้ทั้งสองโหมด: โหมดเดิมคือการอ่านค่าเดิมด้วยสเกลเดียวกัน)"""
    return float(distance_units) * km_per_unit(cfg)


def to_units(km: float, cfg=None) -> float:
    return float(km) / km_per_unit(cfg)


def km_per_day(realm: int, cfg=None) -> float:
    """ความเร็วเดินทางจริงของผู้ที่อยู่ขั้น `realm` ในโหมดดาวเคราะห์ (ยังไม่คูณฤดู/ร่างกาย)

    เรขาคณิต: v = WALK × GROWTH^realm ค่าตั้ง 30 × 1.45^realm
        ขั้น 0  ปุถุชนเดินเท้า        30 กม./วัน
        ขั้น 9  ยอดโลกมนุษย์         ~850 กม./วัน   (รอบโลกมนุษย์ ~47 วัน)
        ขั้น 19 ยอดแดนเซียน         ~35,000 กม./วัน
        ขั้น 29 ยอดสวรรค์นอกชั้นฟ้า  ~1.4 ล้าน กม./วัน
    """
    cfg = cfg or C
    return cfg.TRAVEL_WALK_KM_PER_DAY * (cfg.TRAVEL_KM_GROWTH ** max(0, int(realm)))


def describe_km(distance_units: float, cfg=None) -> str:
    km = to_km(distance_units, cfg)
    return f"{km:,.0f} กม." if km >= 10 else f"{km:.1f} กม."
