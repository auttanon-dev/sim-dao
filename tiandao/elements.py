# -*- coding: utf-8 -*-
"""ห้าธาตุ — ธาตุประจำตัว ธาตุของวิชา และเรขาคณิตของวงจรเบญจธาตุ

ทำไมถึงคุ้มที่จะเพิ่ม: ก่อนหน้านี้ "ธาตุ" มีอยู่แค่ในคำบรรยายวิชา ("สร้างรากฐานธาตุไฟ")
ไม่มีใครอ่านมันได้ การเลือกวิชาจึงเป็นการสุ่มล้วน และวัดจริงได้ว่า **ฝึกวิชาพลาด 44%**
(60 จาก 137 ครั้งในบันทึกผู้มีจิตใจ) ซึ่งเป็นการกระทำที่ถูกเลือกมากที่สุดในโลกด้วย
เมื่อคนเลือกวิชาที่ถูกกับธาตุของตัวเอง ความล้มเหลวจะกลายเป็น **ผลของการเลือก** ไม่ใช่
ลูกเต๋าล้วนๆ และตัวละครสองคนที่เจอสถานการณ์เดียวกันจะเดินคนละทางเพราะธาตุไม่เหมือนกัน

เรขาคณิตที่ทำให้ทุกอย่างลงตัวเอง
------------------------------
วางห้าธาตุบนวงกลมตาม **วงจรเกิด** (相生) ห่างกันจุดละ 72°

        ไม้ ──► ไฟ ──► ดิน ──► ทอง ──► น้ำ ──► (ไม้)

แล้วมุมต่างเฟสระหว่างสองธาตุ = 72° x จำนวนก้าวที่สั้นที่สุดบนวงกลมนั้น ผลที่ได้คือ

    ธาตุเดียวกัน       0 ก้าว -> 0°    -> cos = +1.00   เสริมกันเต็มที่
    วงจรเกิด           1 ก้าว -> 72°   -> cos = +0.31   ส่งเสริมกันเล็กน้อย
    วงจรข่ม (相克)     2 ก้าว -> 144°  -> cos = -0.81   หักล้างกันรุนแรง

**คู่ข่มทั้งห้าคู่ของตำราออกมาเป็น "ห่างกันสองก้าว" พอดีทุกคู่** โดยไม่ต้องเขียนตารางข่ม
แยกต่างหาก — ไม้ข่มดิน · ดินข่มน้ำ · น้ำข่มไฟ · ไฟข่มทอง · ทองข่มไม้ ทั้งหมดคือเส้นทแยง
ของรูปดาวห้าแฉกที่ลากอยู่ในวงกลมนี้ จักรวาลวิทยาจีนกับการแทรกสอดของคลื่นจึงเป็นเรื่อง
เดียวกันพอดี และค่า cos ที่ได้ก็เอาไปเข้าสูตรคลื่นใน physics.py ได้ตรงๆ

ไฟล์นี้ไม่ดึง rng เว้นแต่ `roll()` ซึ่งเรียกตอนเกิดครั้งเดียว
"""
import math

# เรียงตาม **วงจรเกิด** เท่านั้น ลำดับนี้คือสิ่งที่ทำให้วงจรข่มโผล่มาเองที่ระยะสองก้าว
GEN_ORDER = ("ไม้", "ไฟ", "ดิน", "ทอง", "น้ำ")
ELEMENTS = GEN_ORDER
_IDX = {e: i for i, e in enumerate(GEN_ORDER)}
STEP_DEGREES = 72.0

# คำที่บ่งบอกธาตุของวิชา — อ่านจากชื่อและคำบรรยายที่เขียนไว้อยู่แล้ว ไม่ต้องไปไล่ติดป้ายทีละวิชา
# เรียงตามลำดับที่ตรวจ: คำเฉพาะเจาะจงมาก่อนคำกว้าง
_CLUES = (
    ("ไฟ", ("เพลิง", "อัคนี", "อัคคี", "ไฟ", "เผา", "ลาวา", "ภูเขาไฟ", "แสงอาทิตย์", "ร้อน")),
    ("น้ำ", ("วารี", "น้ำ", "สายฝน", "พิรุณ", "เยือกแข็ง", "น้ำแข็ง", "หิมะ", "สมุทร",
             "คลื่น", "หมอก", "เย็น", "จันทร", "เลือด", "โลหิต")),
    ("ทอง", ("กระบี่", "ดาบ", "โลหะ", "เหล็ก", "ทอง", "สัมฤทธิ์", "เงิน", "ศาสตรา", "เข็ม",
             "อาวุธ", "ธนู", "ดรรชนี", "แหลม", "คม")),
    ("ไม้", ("ไม้", "ป่า", "พฤกษ", "ต้นไม้", "ใบ", "ดอก", "สมุนไพร", "ยา", "ฟื้นฟู", "รักษา",
             "ชีวิต", "เถาวัลย์", "เขียว")),
    ("ดิน", ("ศิลา", "หิน", "ผา", "ดิน", "ภูผา", "แผ่นดิน", "กำแพง", "ทราย", "ค่ายกล",
             "ป้องกัน", "ตรึง", "หนัก", "ภูเขา")),
)

# สายวิชาที่มีธาตุประจำตัวชัดอยู่แล้ว ใช้เป็นชั้นสำรองเมื่อคำในชื่อไม่บอกอะไร
_LINE_ELEMENT = {
    "กระบี่": "ทอง", "ดาบ": "ทอง", "กระบี่บิน": "ทอง", "กระบี่โค้ง": "ทอง",
    "กระบี่กระบอง": "ทอง", "ธนู": "ทอง", "ดรรชนี": "ทอง", "อาวุธลับ": "ทอง",
    "รักษา": "ไม้", "ฟื้นฟู": "ไม้", "ปรุงยา": "ไม้", "ชาแมน": "ไม้",
    "ป้องกัน": "ดิน", "ค่ายกล": "ดิน", "เวททราย": "ดิน", "กายภาพ": "ดิน",
    "หุ่นกล": "ดิน", "มวยปล้ำ": "ดิน", "กระบอง": "ดิน",
    "เวท": "ไฟ", "หมัด": "ไฟ", "ฝ่ามือ": "ไฟ", "มวยไทย": "ไฟ", "ทำลายล้าง": "ไฟ",
    "ท่าร่าง": "น้ำ", "ซ่อนตัว": "น้ำ", "ลอบสังหาร": "น้ำ", "จำแลง": "น้ำ",
    "เชิดศพ": "น้ำ", "วิญญาณ": "น้ำ", "จิตวิญญาณ": "น้ำ", "จิต": "น้ำ", "สมาธิ": "น้ำ",
}


def phase_degrees(a: str, b: str) -> float:
    """มุมต่างเฟสระหว่างสองธาตุ — 0° เสริมกัน · 72° ส่งเสริม · 144° ข่มกัน

    ธาตุที่ไม่รู้จัก (ตัวละครเก่าจากเซฟก่อนมีระบบนี้) ถือว่าเป็นกลาง 90° = ไม่เกี่ยวกัน
    ซึ่งทำให้ทุกสูตรที่ใช้ cos ของมันได้ผลเป็นศูนย์พอดี = เหมือนไม่มีระบบธาตุ
    """
    ia, ib = _IDX.get(a), _IDX.get(b)
    if ia is None or ib is None:
        return 90.0
    d = abs(ia - ib)
    steps = min(d, len(GEN_ORDER) - d)      # ระยะที่สั้นที่สุดบนวงกลม: 0, 1 หรือ 2
    return STEP_DEGREES * steps


def affinity(a: str, b: str) -> float:
    """cos ของมุมต่างเฟส — +1 เสริมเต็ม · +0.31 ส่งเสริม · -0.81 ข่ม · 0 ไม่เกี่ยวกัน"""
    return math.cos(math.radians(phase_degrees(a, b)))


def generates(a: str) -> str:
    """ธาตุที่ a ให้กำเนิด (ไม้ให้กำเนิดไฟ)"""
    i = _IDX.get(a)
    return GEN_ORDER[(i + 1) % len(GEN_ORDER)] if i is not None else ""


def overcomes(a: str) -> str:
    """ธาตุที่ a ข่ม (ไม้ข่มดิน) — คือการก้าวไปสองก้าวบนวงจรเกิด"""
    i = _IDX.get(a)
    return GEN_ORDER[(i + 2) % len(GEN_ORDER)] if i is not None else ""


def relation_words(a: str, b: str) -> str:
    """อธิบายความสัมพันธ์เป็นคำ — ใช้ทั้งในพรอมต์และหน้าอ่าน"""
    if not a or not b or a not in _IDX or b not in _IDX:
        return "ไม่เกี่ยวข้องกัน"
    if a == b:
        return "ธาตุเดียวกัน"
    if generates(a) == b:
        return f"{a}ให้กำเนิด{b}"
    if generates(b) == a:
        return f"{b}ให้กำเนิด{a}"
    if overcomes(a) == b:
        return f"{a}ข่ม{b}"
    return f"{b}ข่ม{a}"


def of_skill(name: str, line: str = "", effect: str = "") -> str:
    """ธาตุของวิชาหนึ่ง — อ่านจากชื่อและคำบรรยายที่ผู้เขียนใส่ไว้อยู่แล้ว

    สามชั้น: คำในชื่อ -> คำในคำบรรยาย -> สายของวิชา -> สุดท้ายกระจายตามชื่อแบบคงที่
    ชั้นสุดท้ายใช้ hash ของชื่อเพื่อให้ผลเหมือนเดิมทุกครั้งที่รัน (ไม่ใช่ rng และไม่ใช่
    `hash()` ของไพธอนซึ่งสุ่ม seed ใหม่ทุกโพรเซส)
    """
    text = name or ""
    for el, clues in _CLUES:
        if any(c in text for c in clues):
            return el
    body = effect or ""
    for el, clues in _CLUES:
        if any(c in body for c in clues):
            return el
    if line in _LINE_ELEMENT:
        return _LINE_ELEMENT[line]
    total = sum(ord(ch) for ch in text) if text else 0
    return GEN_ORDER[total % len(GEN_ORDER)]


_SKILL_ELEMENT = {}


def skill_element(name: str) -> str:
    """ธาตุของวิชาตามชื่อ — คิดครั้งเดียวแล้วจำไว้ (ตารางวิชาไม่เปลี่ยนระหว่างรัน)"""
    if not _SKILL_ELEMENT:
        from .skills import SKILLS
        for row in SKILLS:
            _SKILL_ELEMENT[row[0]] = of_skill(row[0], row[1], row[4])
    if name in _SKILL_ELEMENT:
        return _SKILL_ELEMENT[name]
    return of_skill(name)


def roll(ch, rng, parents=()):
    """ธาตุประจำตัวตอนเกิด — สืบจากพ่อแม่เป็นหลัก ที่เหลือคือสิ่งที่ฟ้าให้มา

    ทำไมต้องสืบ: ตระกูลในนิยายแนวนี้มี "สายธาตุ" ของตัวเอง และมันทำให้การเลือกคู่ การรับศิษย์
    และความบาดหมางระหว่างตระกูล มีเหตุผลเชิงกลไกรองรับ ไม่ใช่แค่ชื่อสกุลที่ต่างกัน
    """
    pool = [getattr(p, "element", "") for p in parents if getattr(p, "element", "")]
    if pool and rng.random() < 0.6:
        ch.element = rng.choice(pool)
    else:
        ch.element = rng.choice(GEN_ORDER)
    return ch.element


def ensure(ch) -> str:
    """เติมธาตุให้ตัวละครจากเซฟเก่าโดยไม่ใช้ rng — คงที่ตาม cid"""
    el = getattr(ch, "element", "")
    if el in _IDX:
        return el
    ch.element = GEN_ORDER[int(getattr(ch, "cid", 0)) % len(GEN_ORDER)]
    return ch.element


def words(ch) -> str:
    el = ensure(ch)
    return f"ธาตุ{el} (ให้กำเนิดธาตุ{generates(el)} · ข่มธาตุ{overcomes(el)})"


def best_of(pool, element, key=lambda x: x[0]):
    """เรียงวิชาจาก 'ถูกกับธาตุข้า' ไปหา 'ขัดกับธาตุข้า' — ใช้ตอนเลือกว่าจะฝึกอะไร"""
    return sorted(pool, key=lambda x: (-affinity(element, skill_element(key(x))), key(x)))


def clash_edge(a: str, b: str) -> float:
    """ความได้เปรียบของธาตุ a เมื่อปะทะธาตุ b — มีทิศทาง ต่างจาก `affinity` ที่สมมาตร

    `affinity` บอกว่าสองคลื่นเข้ากันแค่ไหน (เท่ากันทั้งสองฝั่ง) แต่การปะทะมีผู้ข่มและผู้ถูกข่ม
    น้ำกับไฟอยู่ห่างกัน 144° เท่ากันทั้งคู่ แต่ **น้ำดับไฟ ไม่ใช่ไฟดับน้ำ**

    ขนาดของค่ายืมมาจากเรขาคณิตเดิม ไม่ได้ตั้งใหม่
        |cos 144°| = 0.809  -> คู่ข่ม
        |cos 72°|  = 0.309  -> คู่เกิด (ผู้ให้กำเนิดเสียเปรียบ เพราะกำลังหล่อเลี้ยงอีกฝ่ายอยู่)
    """
    if not a or not b or a not in _IDX or b not in _IDX or a == b:
        return 0.0
    strong = abs(math.cos(math.radians(2 * STEP_DEGREES)))   # 0.809
    weak = abs(math.cos(math.radians(STEP_DEGREES)))         # 0.309
    if overcomes(a) == b:
        return strong
    if overcomes(b) == a:
        return -strong
    if generates(a) == b:
        return -weak          # ข้าหล่อเลี้ยงเขาอยู่ กำลังไหลออกจากตัวข้า
    return weak               # เขาหล่อเลี้ยงข้า
