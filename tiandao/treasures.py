def aid_of(ch, items, path: str = None):
    """สมบัติช่วยบำเพ็ญที่ตัวละครถืออยู่ (ชิ้นแรกที่เจอ) — คืน None ถ้าไม่มี

    รับ `items` เป็นตัวแมป iid -> Item ของซิม (ไม่ import sim เข้ามาที่นี่ กันวงจร import)
    """
    for iid in getattr(ch, "items", ()):  # ตัวละครบางตัวถูกสร้างก่อนมีฟิลด์ items
        it = items.get(iid)
        if it is None:
            continue
        aid = CULTIVATION_AIDS.get(it.name)
        if aid and (path is None or aid["path"] == path):
            return aid
    return None


def has_anti_chaos_treasure(ch, items) -> bool:
    return any(items.get(i) is not None and items[i].name == ANTI_CHAOS_TREASURE
               for i in getattr(ch, "items", ()))
