def date_words(day: int) -> str:
    """วันที่ในปฏิทินของโลก — ปีละ 365 วัน เดือนละ 30 (เดือน 12 ยาว 35)"""
    y, doy = divmod(max(0, int(day)), 365)
    m = min(12, doy // 30 + 1)
    dd = doy - (m - 1) * 30 + 1
    return f"ปีที่ {y} เดือน {m} วันที่ {dd}"
