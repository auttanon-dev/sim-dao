def ensure(ch):
    """ตัวละครจาก save เก่ายังไม่มีใจ — เติมให้โดย **ไม่ใช้ rng** (เรียกกลางรันได้ไม่พังความคงที่)

    ค่าที่ได้อนุมานจากนิสัยที่เขามีอยู่แล้ว บวก offset จาก cid ให้ไม่เท่ากันทุกคน
    """
    if getattr(ch, "emotions", None) and getattr(ch, "desires", None):
        if not getattr(ch, "emo_base", None):
            ch.emo_base = dict(ch.emotions)
        if not getattr(ch, "des_base", None):
            ch.des_base = dict(ch.desires)
        if getattr(ch, "emo_day", None) is None:
            ch.emo_day = getattr(ch, "last_day", 0)
        return ch
    fear = getattr(ch, "fear", 0.5)
    greed = getattr(ch, "greed", 0.5)
    comp = getattr(ch, "compassion", 0.5)
    amb = getattr(ch, "ambition", 50) / 100.0
    loy = getattr(ch, "loyalty", 50) / 100.0
    j = ((getattr(ch, "cid", 0) * 37) % 41) / 100.0 - 0.2   # -0.20..+0.20 คงที่ต่อคน
    ch.emotions = {
        "ยินดี": _c(0.40 + j), "โกรธ": _c(0.30 - j), "เศร้า": _c(0.30 + j * 0.5),
        "กลัว": _c(fear + j * 0.5), "รัก": _c(comp - j * 0.5),
        "ชิงชัง": _c(1.0 - comp + j * 0.4), "อยาก": _c(greed + j * 0.4),
    }
    ch.desires = {
        "อยากมีชีวิต": _c(0.5 + fear * 0.3 + j * 0.3), "อยากรู้": _c(0.45 - j),
        "อยากได้": _c(greed + j * 0.3), "อยากเป็นใหญ่": _c(amb + j * 0.3),
        "อยากเป็นที่รัก": _c((loy + comp) / 2.0 - j * 0.3), "อยากพ้นทุกข์": _c(0.4 + j),
    }
    ch.emo_base = dict(ch.emotions)
    ch.des_base = dict(ch.desires)
    ch.emo_day = getattr(ch, "last_day", 0)
    return ch


# ---------------------------------------------------------------- เวลาผ่านไป
def decay(ch, day):
    """ดึงอารมณ์กลับเข้าหาฐานใจตามเวลาที่ผ่าน — คิดแบบ lazy ตอนจะใช้ค่า ไม่ต้องวนทุกคนทุกวัน"""
    ensure(ch)
    dt = day - getattr(ch, "emo_day", day)
    if dt <= 0:
        return ch
    f = 0.5 ** (dt / EMO_HALF)
    g = 0.5 ** (dt / DES_HALF)
    eb, db = ch.emo_base, ch.des_base
    ch.emotions = {k: _c(eb.get(k, 0.5) + (v - eb.get(k, 0.5)) * f)
                   for k, v in ch.emotions.items()}
    ch.desires = {k: _c(db.get(k, 0.5) + (v - db.get(k, 0.5)) * g)
                  for k, v in ch.desires.items()}
    ch.emo_day = day
    return ch


