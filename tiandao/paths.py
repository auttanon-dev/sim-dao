"""สายบำเพ็ญ กาย / จิต — คนหนึ่งฝึกได้หลายสาย และแต่ละสายให้ของคนละอย่าง

ทำไมต้องแยกเป็นไฟล์ ไม่ใส่ลง skills.py
---------------------------------------------------------------------------------------------
`skills.py` เป็น **ตารางข้อมูลดิบ** ของ 135 วิชา (ชื่อ, สาย, tier, เกรด, ผล, แก้ทางโกลาหลได้ไหม)
ไม่มีตรรกะอยู่ในนั้นเลยแม้แต่บรรทัดเดียว ส่วนไฟล์นี้เป็น **การตีความ** ข้อมูลนั้นว่าสายไหนนับเป็น
การบำเพ็ญทางกายหรือทางจิต ซึ่งเป็นเรื่องของกฎโลก ไม่ใช่ของตารางวิชา — และเป็นสิ่งที่จะถูกปรับจูน
ต่อไปเรื่อยๆ โดยไม่ควรต้องไปแตะรายการวิชา 135 บรรทัดนั้นซ้ำ

หลักการออกแบบ: **ไม่มีสายไหนดีกว่าสายไหน มีแต่ดีคนละเรื่อง**
  กาย    ทนทาน ร่างไม่โรยเร็ว พลังดิบไม่ต้องพึ่งความเข้าใจ — แต่เพดานพลังตันกว่า
  จิต    ความเข้าใจแปลงเป็นพลังได้มากกว่า ข้ามขั้นง่ายกว่า — แต่ร่างเปราะและเสื่อมเร็ว
  สมดุล  ไม่โดดเด่นทั้งสองด้าน แต่เป็นสายเดียวที่ยืนต้านเผ่าโกลาหลได้จริง เพราะการบิดเบือนของ
         มันเล่นงานทั้งกายและใจพร้อมกัน คนที่ขาดด้านใดด้านหนึ่งจะถูกเจาะที่ด้านนั้นเสมอ

"สยาม เน้นกายเป็นหลัก แต่ก็มีสายจิตวิญญาณ" — เป็นเรื่องของ *สัดส่วนวิชาในแดนนั้น* ไม่ใช่กฎตายตัว
ว่าใครเกิดแดนไหนต้องฝึกอะไร ตารางด้านล่างจึงจัดตาม "สายวิชา" ล้วนๆ ตัวละครแดนไหนก็เลือกได้เอง
"""
from typing import Dict, Tuple

from .skills import SKILLS

# ---------------------------------------------------------------- จัดสายวิชาเป็นกาย/จิต
# เกณฑ์: วิชาที่ผลของมันเกิดกับ "เนื้อตัวและการเคลื่อนไหว" = กาย
#        วิชาที่ผลของมันเกิดกับ "ปราณ ดวงจิต กฎเกณฑ์ หรือสิ่งที่อยู่นอกตัว" = จิต
BODY_LINES = frozenset({
    "ฝ่ามือ", "หมัด", "กายภาพ", "มวยไทย", "มวยปล้ำ", "กระบอง", "กระบี่กระบอง",
    "ท่าร่าง", "ป้องกัน", "ดาบ", "กระบี่", "กระบี่โค้ง", "ธนู", "ดรรชนี",
    "วัชระ", "อาวุธลับ", "ลอบสังหาร", "ซ่อนตัว", "กาย/ธาตุ",
})
SPIRIT_LINES = frozenset({
    "เวท", "เวททราย", "จิต", "จิตวิญญาณ", "วิญญาณ", "สมาธิ", "สัมผัส", "เนตร",
    "พิธีกรรม", "องเมียวจิ", "ชาแมน", "ตันตระ", "อัญเชิญ", "ควบคุม", "เสียง",
    "คลื่นเสียง", "จำแลง", "ค่ายกล", "ดูดซับ", "กฎเกณฑ์", "พระผู้สร้าง",
    "ทำลายล้าง", "ธาตุสวรรค์", "ธาตุ", "แปรธาตุ", "ปรุงยา", "รักษา", "ฟื้นฟู",
    "กระบี่บิน", "สัตว์อสูร", "มิติ", "เวลา", "วัฏจักร", "หุ่นกล", "เชิดศพ",
})

# ตรวจตั้งแต่โหลดโมดูลว่าไม่มีสายไหนตกหล่นหรือถูกจัดซ้ำสองฝั่ง — ถ้าเพิ่มวิชาสายใหม่ใน skills.py
# แล้วลืมมาจัดที่นี่ จะรู้ทันทีตอน import ไม่ใช่ไปเงียบๆ กลายเป็น "ไม่มีสาย" กลางซิม
_ALL_LINES = {s[1] for s in SKILLS}
_UNMAPPED = _ALL_LINES - BODY_LINES - SPIRIT_LINES
_BOTH = BODY_LINES & SPIRIT_LINES
assert not _UNMAPPED, f"สายวิชาที่ยังไม่ได้จัดเป็นกาย/จิต: {sorted(_UNMAPPED)}"
assert not _BOTH, f"สายวิชาที่ถูกจัดซ้ำทั้งสองฝั่ง: {sorted(_BOTH)}"

# น้ำหนักตามเกรดวิชา — วิชาขั้นสูงบอกทิศทางของคนคนนั้นชัดกว่าวิชาขั้นต่ำสิบวิชารวมกัน
_GRADE_W = (1.0, 1.8, 3.0)
_LINE_OF: Dict[str, str] = {s[0]: s[1] for s in SKILLS}
_GRADE_OF: Dict[str, int] = {s[0]: s[3] for s in SKILLS}

BALANCE_AT = 0.35     # ทั้งสองด้านต้องมีสัดส่วนอย่างน้อยเท่านี้ถึงนับว่า "สมดุล"
MIN_WEIGHT = 2.0      # น้ำหนักรวมต่ำกว่านี้ถือว่ายังไม่พอบอกได้ว่าเป็นสายอะไร


def weights(ch) -> Tuple[float, float]:
    """(น้ำหนักทางกาย, น้ำหนักทางจิต) จากวิชาที่รู้จริง ไม่ใช่จากฟิลด์ที่ประกาศไว้เฉยๆ

    ตั้งใจคำนวณสดจาก `ch.skills` ทุกครั้ง ไม่เก็บเป็นฟิลด์ในตัวละคร เพราะ (ก) มันเปลี่ยนทุกครั้ง
    ที่ฝึกวิชาใหม่ ถ้าเก็บไว้ก็ต้องคอยอัปเดตให้ครบทุกทางที่วิชาเพิ่มได้ ซึ่งเป็นบั๊กที่รอเกิด และ
    (ข) เซฟเก่าที่ไม่มีฟิลด์นี้ยังอ่านได้ทันทีโดยไม่ต้อง migrate
    """
    body = spirit = 0.0
    for name in ch.skills:
        line = _LINE_OF.get(name)
        if line is None:
            continue
        w = _GRADE_W[min(_GRADE_OF.get(name, 0), len(_GRADE_W) - 1)]
        if line in BODY_LINES:
            body += w
        elif line in SPIRIT_LINES:
            spirit += w
    return body, spirit


def shares(ch) -> Tuple[float, float]:
    """สัดส่วน (กาย, จิต) รวมกันได้ 1.0 — คืน (0, 0) ถ้ายังไม่มีวิชามากพอจะบอกได้"""
    body, spirit = weights(ch)
    total = body + spirit
    if total < MIN_WEIGHT:
        return 0.0, 0.0
    return body / total, spirit / total


def path_of(ch) -> str:
    """ชื่อสายที่อ่านออกได้ ใช้ทั้งในกฎและในนิยาย"""
    b, s = shares(ch)
    if b == 0.0 and s == 0.0:
        return "ยังไม่แน่ชัด"
    if b >= BALANCE_AT and s >= BALANCE_AT:
        return "สมดุลกายจิต"
    return "กายบำเพ็ญ" if b > s else "จิตบำเพ็ญ"


def is_balanced(ch) -> bool:
    b, s = shares(ch)
    return b >= BALANCE_AT and s >= BALANCE_AT


def line_path(line: str) -> str:
    """สายวิชาหนึ่งสายนับเป็นทางไหน — ใช้ตอนเลือกวิชาที่จะฝึกต่อ"""
    if line in BODY_LINES:
        return "กาย"
    if line in SPIRIT_LINES:
        return "จิต"
    return "-"


def skill_path(skill_name: str) -> str:
    return line_path(_LINE_OF.get(skill_name, ""))

# ---------------------------------------------------------------- ความถนัดประจำแดน
# "สยามเน้นฝึกวิชาทางกายเป็นหลัก แต่ก็มีสายจิตวิญญาณ" — ตัวเลขคือ **โอกาสที่จะเอนไปทางกาย**
# ตอนเลือกวิชาใหม่ ไม่ใช่กฎบังคับ: 0.72 แปลว่าโดยเฉลี่ยราว 7 ใน 10 ครั้งคนแดนนั้นจะหยิบวิชาสายกาย
# ส่วนที่เหลือก็ยังเป็นสายจิตได้ตามปกติ และคนที่ฝึกสลับไปมาจนสมดุลก็มีจริง (ดู is_balanced)
# แดนที่ไม่อยู่ในตารางนี้ = 0.5 คือไม่เอนไปทางไหนเลย
REALM_BODY_BIAS = {
    "siam": 0.72,       # มวยไทย กระบี่กระบอง — ร่างกายคือสนามฝึกหลัก แต่มีสายพิธีกรรม/จิตด้วย
    "steppe": 0.70,     # ขี่ยิงธนู มวยปล้ำ — แต่มีสายชาแมนคุยกับฟ้าดิน
    "fusang": 0.62,     # ดาบและท่าร่าง — ถ่วงด้วยสายองเมียวจิที่เป็นจิตล้วน
    "bharata": 0.30,    # โยคะ ตันตระ สมาธิ — เน้นจิตเป็นหลัก กายเป็นทางรอง
    "oasis": 0.42,      # เวททรายและการอัญเชิญ เอนไปทางจิตเล็กน้อย
    "ocean": 0.38,      # วิชาสายน้ำและการควบคุมปราณ
    "abyss": 0.55,      # แดนใต้พิภพ ต้องทนสภาพก่อน จึงเอนไปทางกายนิดหน่อย
    "mara": 0.45,
}
DEFAULT_BODY_BIAS = 0.5


def body_bias(place_key) -> float:
    return REALM_BODY_BIAS.get(place_key, DEFAULT_BODY_BIAS)


def prefer_pool(pool, place_key, rng):
    """คัดวิชาในกองให้เหลือเฉพาะทางที่แดนนั้นถนัด — คืนกองเดิมถ้าทางนั้นไม่มีวิชาให้เลือกเลย

    `pool` เป็นรายการทูเพิลของ skills.py (ชื่อ, สาย, tier, เกรด, ผล, แก้ทางโกลาหล)
    """
    want = "กาย" if rng.random() < body_bias(place_key) else "จิต"
    narrowed = [x for x in pool if line_path(x[1]) == want]
    return narrowed or pool
