def _org_presence(sim):
    """ที่ตั้งที่ "มีคนของสำนักยืนอยู่จริง" — สร้างครั้งเดียวต่อวัน แล้วใช้ร่วมกันทั้งวัน

    ของเดิมวน sim.orgs (151 สำนัก) x สมาชิกทุกคน ใหม่ทุกครั้งที่ใครสักคนคิดจะ "เข้าสำนัก"
    วัดด้วย cProfile ที่ปีที่ 1,171: 2.28 วินาทีจาก 21.7 = 10% ของเวลาซิมทั้งหมด
    """
    # แคชนานเป็นสิบวัน ไม่ใช่วันเดียว — วันของซิมเดินเกือบทุกเหตุการณ์ แคชรายวันจึงเท่ากับไม่มีแคช
    # วัดจริงที่ปีที่ 513: สร้างใหม่ 1,935 ครั้งต่อ 3,000 เหตุการณ์ = 51% ของเวลาซิมทั้งหมด
    # (ทางเร็วจริงคือดูจากคนที่ยืนอยู่ตรงนั้นแทน — ดู weigh() ที่ส่ง others เข้ามา)
    cache = getattr(sim, "_org_presence_cache", None)
    if cache is not None and sim.day - cache[0] < 30:
        return cache[1]
    seen = set()
    cast = sim.cast
    n = len(cast)
    for o in sim.orgs:
        if not o.alive:
            continue
        wid, key_mara = o.world_id, o.mara
        for m in o.members:
            if m < n:
                mem = cast[m]
                if mem.alive:
                    seen.add((wid, mem.place, key_mara))
    sim._org_presence_cache = (sim.day, seen)
    return seen


def weigh(ch, sim, table, has_others, loot_nearby=None,
          debtor_nearby=None, secret_available=None, others=None):
    """คืน dict ของ kind -> น้ำหนัก หลังผ่านสามเลเยอร์

    สามค่าท้ายคือ "เงื่อนไขที่ weigh มองไม่เห็นเอง" ผู้เรียกคำนวณให้ (None = ไม่รู้ ไม่ต้องกรอง)
      loot_nearby      — มีใครแถวนี้ถือของที่ชิงได้ไหม
      debtor_nearby    — มีคู่กรณีที่ยังค้างเรื่องกันอยู่แถวนี้ไหม
      secret_available — มีแดนลับที่ผนึกเสื่อมแล้ว หรือเศษวิชาที่ยังไม่มีใครเก็บ อยู่ให้ค้นไหม
    weigh ไม่ควรไปเรียก social_pool เองเพราะมันใช้ rng — ผลจะไม่คงที่และเทสต์จะเชื่อไม่ได้
    """
    w = {}
    for e in table:
        if e["tgt"] and not has_others:
            continue
        w[e["kind"]] = float(e["w"])
        
    # ---- เลเยอร์ 0: อาชีพและนิสัย ----
    prof = getattr(ch, "profession", "ผู้ฝึกตน")
    for kind, bonus in PROFESSION_WORK.get(prof, ()):
        w[kind] = w.get(kind, 0.0) + bonus
    if prof in MUNDANE_PROFESSIONS:
        # คนที่มีอาชีพสามัญไม่ได้ใช้ชีวิตแบบผู้ฝึกตน — กดเรื่องบำเพ็ญลงมาก แต่ไม่ถึงศูนย์
        for k in ("บำเพ็ญ", "ข้ามขั้น", "ล่าอสูร", "ค้นแดนลับ", "ประลอง"):
            if k in w:
                w[k] *= 0.1

    # นิสัยมีผลกับ **ทุกคน** ไม่ใช่เฉพาะ "ผู้ฝึกตน" — เดิมบล็อกนี้อยู่ในสาขา else ของเงื่อนไข
    # `profession != "ผู้ฝึกตน"` แต่วัดจริงจากโลก 513 ปีแล้วพบว่า **ไม่มีใครมีอาชีพ "ผู้ฝึกตน" เลย
    # สักคนเดียว** (36 อาชีพที่มีจริง ไม่มีชื่อนี้อยู่ในนั้น) สาขา else จึงไม่เคยทำงาน แปลว่า
    # ความกลัว/ความโลภ/ความเมตตา ที่สุ่มให้ทุกคนตอนเกิด ไม่เคยมีผลต่อพฤติกรรมใครเลยตลอดมา
    if "จำลองอนาคต" in w:
        # เปิดให้เฉพาะเจ้าของระบบ และเฉพาะตอนที่ภาพยอมเปิดให้เห็น (พ้นคูลดาวน์แล้ว)
        w["จำลองอนาคต"] = 0.0
        if getattr(ch, "system_foresight", False) and getattr(C, "FORESIGHT_ON", True):
            _last = ch.visions[-1]["day"] if getattr(ch, "visions", None) else -10 ** 9
            if sim.day - _last >= C.FORESIGHT_COOLDOWN_DAYS:
                w["จำลองอนาคต"] = C.FORESIGHT_W
    if "ปิดด่าน" in w:
        # ปิดด่าน 3-8 ปีทั้งที่ยังไม่มีอะไรจะทะลวง คือการทิ้งชีวิตไปเปล่าๆ — ต่ำกว่าเกณฑ์จึงเป็นศูนย์
        # ไม่ใช่ "เตี้ยๆ แต่ไม่ศูนย์" เพราะค่าเตี้ยๆ ผิดสองทางพร้อมกัน: เอนจินสุ่มตามน้ำหนักจะได้
        # ปิดด่านมั่วทั้งโลก ส่วนผู้มีจิตใจเห็นเมนูแค่ 12 อันดับแรก ค่าเตี้ยจึง **ไม่เคยโผล่เลย**
        # (วัดจริงปีที่ 104-118: อันดับ 18/18 น้ำหนัก 7.72 โผล่ในเมนูแค่ 2 จาก 60 คน ใช้จริง 0 ครั้ง)
        # พ้นเกณฑ์แล้วจึงไต่ชันไปหา 38 — สูงพอติดห้าอันดับแรกตอนที่มันควรเป็นทางเลือกจริงๆ
        from . import rules as _RS
