# -*- coding: utf-8 -*-
"""ซ่อมเงินในเซฟเก่าที่ถูก "เครื่องปั๊มเงิน" ของสำนักเสกขึ้นมา — รันครั้งเดียว ไม่ใช่กลไกของโลก

ทำไมต้องมีเครื่องมือนี้แทนที่จะเติมใน persist._backfill_new_attrs
----------------------------------------------------------------
การเติม element/mastery ให้เซฟเก่าเป็นการ "เติมสิ่งที่ควรมีอยู่แล้ว" — ไม่มีทางผิด เพราะคนที่
ถือวิชาอยู่ย่อมเคยฝึกมาแล้วอย่างน้อยหนึ่งครั้ง แต่การลบเงินคือการแก้ประวัติศาสตร์ของโลกที่เดิน
มาแล้ว 152 ปี ซึ่งเป็นการตัดสินใจของเจ้าของโลก ไม่ใช่ของโค้ด จึงแยกออกมาเป็นเครื่องมือที่ต้อง
สั่งเอง และเขียนลงไฟล์ใหม่เสมอ (ไม่ทับของเดิม) เว้นแต่จะสั่ง --in-place

บั๊กที่ทำให้ต้องซ่อม
-------------------
โค้ดเดิมตั้ง org.monthly_resource = 10000 ให้ทุกสำนักทุกเดือนโดยไม่มีใครจ่าย สำนักที่มีศิษย์
คนเดียวจึงจ่ายคนนั้น 120,000 ต่อปีจากอากาศ ตอนนี้แก้เป็นวงจรปิด (ศิษย์จ่ายค่าบำรุง → คลัง →
จ่ายคืน) แล้ว เครื่องปั๊มหยุดแล้วจริง — วัดจากเซฟปีที่ 152: monthly_resource เหลือ 0-438
และคลังสำนักใหญ่สุด 292 แต่ **เงินที่ปั๊มไปแล้วยังค้างอยู่ในมือคน**:

    รวมเงินทั้งโลก 6,541,063  ·  เสิ่นอวิ๋น (ขั้น 3) ถือคนเดียว 3,940,297 = 60%
    คนถือเกินแสน 9 คน ถือรวมกัน 5.3 ล้าน = 81% ของเงินทั้งโลก
    Gini 0.975 · รวย 1% ถือ 90.4%

ผลเสียที่จับต้องได้ ไม่ใช่แค่ตัวเลขไม่สวย: เงินเป็นเพดานการประมูล คนที่ถือ 3.9 ล้านชนะประมูล
ทุกครั้งตลอดกาล กลไกประมูลราคาที่สอง (physics.second_price) กับมูลค่าส่วนตัวแบบ log-normal
ที่เพิ่งใส่เข้าไปจึงไม่มีความหมายกับคนที่เหลือทั้งโลก

วิธีซ่อม: บีบปลายบน ไม่ใช่หารทั้งกระดาน
---------------------------------------
    m' = m                                        ถ้า m <= KNEE
    m' = KNEE + (CEIL-KNEE)·(1 - e^{-(m-KNEE)/SCALE})   ถ้า m > KNEE

เป็นฟังก์ชันอิ่มตัวแบบเอกซ์โพเนนเชียล เลือกเพราะ:
  · **เพิ่มทางเดียว** — ใครรวยกว่าก็ยังรวยกว่า อันดับความมั่งคั่งซึ่งเป็นข้อเท็จจริงในเรื่อง
    ไม่ถูกสลับ เสิ่นอวิ๋นยังเป็นคนรวยที่สุดในโลกอยู่ แค่ไม่ใช่ในระดับที่เป็นไปไม่ได้
  · **ต่อเนื่องที่ KNEE** — ไม่มีรอยต่อให้คนสองคนที่รวยพอๆ กันกระโดดห่างกัน
  · **ไม่แตะคนส่วนใหญ่** — ใต้ KNEE ไม่ขยับสักเหรียญ คนจนไม่ได้ถูกลงโทษเพราะบั๊กของสำนัก
  · **มีเพดานแข็ง** — ความมั่งคั่งรวมเข้าใกล้ CEIL แต่ไม่เกิน

ค่าคงที่มาจากการวัด ไม่ได้ตั้งลอยๆ: รันโลก 152 ปีด้วยเศรษฐกิจที่แก้แล้วตั้งแต่ต้น ได้เงินสูงสุด
ทั้งโลก 11,000 และมัธยฐาน 86 จึงใช้ CEIL = 11,000 เป็นเพดาน และ KNEE = 3,000 ซึ่งอยู่เหนือ
กว่าที่คนเกือบทั้งโลกในรันสะอาดเคยไปถึง — เงินที่หามาได้เองจึงรอดทั้งหมด

    python repair_money.py <ไฟล์เซฟ> [--out <ไฟล์ใหม่>] [--in-place] [--dry-run]
"""
import argparse
import math
import statistics as st
import sys

from tiandao import persist

CEIL = 11000.0   # เพดาน = เงินสูงสุดที่โลก 152 ปีซึ่งเศรษฐกิจถูกตั้งแต่ต้นผลิตได้จริง
KNEE = 3000.0    # ใต้เส้นนี้ไม่แตะเลย
SCALE = 20000.0  # ความชันของการบีบเหนือ KNEE


def squash(m: float) -> float:
    if m <= KNEE:
        return m
    return KNEE + (CEIL - KNEE) * (1.0 - math.exp(-(m - KNEE) / SCALE))


def gini(xs):
    xs = sorted(xs)
    n, s = len(xs), sum(xs)
    if n == 0 or s == 0:
        return 0.0
    return (2 * sum((i + 1) * x for i, x in enumerate(xs)) / (n * s)) - (n + 1) / n


def report(alive, label):
    xs = sorted(sum(c.money.values()) for c in alive)
    top = max(1, int(len(xs) * 0.01))
    print(f"{label}: รวม {int(sum(xs)):,} · มัธยฐาน {int(st.median(xs)):,} · "
          f"สูงสุด {int(xs[-1]):,} · Gini {gini(xs):.3f} · "
          f"รวย 1% ถือ {100*sum(xs[-top:])/max(1,sum(xs)):.1f}%")


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("save")
    ap.add_argument("--out", default=None)
    ap.add_argument("--in-place", action="store_true")
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args(argv)

    sim = persist.load_sim(a.save)
    alive = [c for c in sim.cast if c.alive]
    report(alive, "ก่อนซ่อม")

    touched = 0
    # ซ่อมทุกคนในทะเบียน ไม่ใช่แค่คนเป็น — คนตายยังถือเงินติดตัวไปเป็นมรดกของทายาทได้
    # บีบที่ "ความมั่งคั่งรวมของคนคนหนึ่ง" แล้วค่อยหารกลับตามสัดส่วนเดิมของแต่ละแดน
    # ถ้าบีบทีละกระเป๋า คนที่กระจายเงินไว้สามแดนจะเลี่ยงเพดานไปได้สามเท่าโดยอัตโนมัติ
    # และสัดส่วนเดิมต้องคงไว้ เพราะ "เขามีเงินอยู่แดนไหน" เป็นข้อเท็จจริงที่กลไกค้าขายใช้จริง
    for ch in sim.cast:
        total = sum(ch.money.values())
        if total <= KNEE:
            continue
        keep = squash(float(total)) / float(total)
        for wid, m in list(ch.money.items()):
            ch.money[wid] = int(round(m * keep))
        touched += 1
    report([c for c in sim.cast if c.alive], "หลังซ่อม")
    print(f"คนที่ถูกบีบ: {touched}")

    if a.dry_run:
        print("(--dry-run — ไม่ได้เขียนไฟล์)")
        return 0
    out = a.save if a.in_place else (a.out or a.save + ".repaired")
    persist.save_sim(sim, out)
    print(f"เขียนลง {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
