def react(ch, kind, outcome, tags=(), day=None, role="actor"):
    """ใจขยับตามสิ่งที่พบเจอ — ไม่ใช้ rng เลย เรียกจาก Sim.emit ได้ทุกเหตุการณ์

    role="target" คือฝ่ายที่ถูกกระทำ: เขาไม่รับตารางของ "ผู้ลงมือ" แต่รับปฏิกิริยาของผู้ถูก
    กระทำแทน และรับผลจาก outcome/tag แค่ครึ่งเดียว (เขารู้ผลน้อยกว่าคนที่ลงมือเอง)
    """
    if ch is None or not getattr(ch, "alive", True):
        return {}
    if not getattr(ch, "sentient", True):
        return {}
    if day is not None:
        decay(ch, day)
    else:
        ensure(ch)
    acc = {}

    def add(d, scale=1.0):
        for k, v in d.items():
            acc[k] = acc.get(k, 0.0) + v * scale

    share = TARGET_SHARE if role == "target" else 1.0
    if role == "target":
        if kind in HOSTILE_KINDS:
            add(TARGET_HOSTILE)
        elif kind in WARM_KINDS:
            add(TARGET_WARM)
        else:
            add(BY_KIND.get(kind, {}), 0.5)
    else:
        add(BY_KIND.get(kind, {}))
    if role == "target" and outcome in TARGET_OUTCOME:
        add(TARGET_OUTCOME[outcome])
    if outcome in BY_OUTCOME:
        add(BY_OUTCOME[outcome], share)
    elif outcome in NUISANCE:
        acc["เศร้า"] = acc.get("เศร้า", 0.0) + 0.02 * share
    for t in tags or ():
        if t in BY_TAG:
            add(BY_TAG[t], share * 0.6)

    em, de, eb, db = ch.emotions, ch.desires, ch.emo_base, ch.des_base
    moved = {}
    for k, dv in acc.items():
        if not dv:
            continue
        if k in em:
            em[k] = _c(em[k] + dv)
            eb[k] = _c(eb.get(k, em[k]) + dv * EMO_DRIFT)   # เรื่องที่เจอซ้ำๆ เปลี่ยนฐานใจจริง
        elif k in de:
            de[k] = _c(de[k] + dv)
            db[k] = _c(db.get(k, de[k]) + dv * EMO_DRIFT)
        moved[k] = dv
    if outcome in CALM or kind == "บำเพ็ญ":
        for k in em:
            em[k] = _c(em[k] + (eb.get(k, em[k]) - em[k]) * CALM_PULL)
    return moved


# ---------------------------------------------------------------- อ่านออกมาเป็นคำ
_LEVEL = ((0.85, "ท่วมท้น"), (0.7, "รุนแรง"), (0.55, "มาก"), (0.4, "พอประมาณ"))


def _level(v):
    for bar, word in _LEVEL:
        if v >= bar:
            return word
    return "เบาบาง"


def _contrast(v, vals):
    """ความเด่นของค่านี้ "เทียบกับใจดวงเดียวกัน" ไม่ใช่เทียบกับเลขดิบ

    ทำไมต้องเทียบในตัวเอง: คนอายุสองร้อยปีผ่านเรื่องมามาก ค่าดิบทุกช่องสูงหมด ถ้าใช้เลขดิบ
    ทุกคนแก่ๆ จะถูกบรรยายว่า "โกรธท่วมท้น กลัวท่วมท้น" พร้อมกัน — ซึ่งไม่ได้บอกอะไรเลยว่า
    ใจเขาเอียงไปทางไหน สิ่งที่คนเล่าเรื่องต้องรู้คือ "อารมณ์ไหนครอบอีกหกอารมณ์ของเขาอยู่"
    """
    avg = sum(vals) / max(1, len(vals))
    return _c(0.5 + (v - avg))


def emotion_words(ch, top=2):
    """อารมณ์ที่เด่นที่สุดตอนนี้ เป็นคำ — ใช้ในพรอมต์และหน้าอ่าน"""
    ensure(ch)
    vals = list(ch.emotions.values())
    rank = sorted(ch.emotions.items(), key=lambda kv: (-kv[1], kv[0]))
    strong = [f"{k}{_level(_contrast(v, vals))}" for k, v in rank[:top] if v >= 0.4]
    if not strong:
        return "ใจสงบ ไม่มีอารมณ์ใดเด่น"
    return " · ".join(strong)


def desire_words(ch, top=2):
    """แรงขับที่แรงที่สุดตอนนี้ เป็นคำ"""
    ensure(ch)
    vals = list(ch.desires.values())
    rank = sorted(ch.desires.items(), key=lambda kv: (-kv[1], kv[0]))
    return " · ".join(f"{k} ({_level(_contrast(v, vals))})" for k, v in rank[:top])


def stirred(ch, bar=0.15):
    """อารมณ์ที่ "สูงกว่าใจปกติของตัวเอง" ตอนนี้ — คือส่วนที่เหตุการณ์เพิ่งทำไว้ ยังไม่สงบ"""
    ensure(ch)
    out = []
    for k, v in ch.emotions.items():
        d = v - ch.emo_base.get(k, v)
        if d >= bar:
            out.append(k)
    return out


def state(ch):
    """ใจทั้งดวงแบบ dict — สำหรับบันทึก/หน้าอ่าน/เทสต์"""
    ensure(ch)
    return {"อารมณ์": dict(ch.emotions), "ปรารถนา": dict(ch.desires),
            "ฐานใจ": dict(ch.emo_base), "คำ": emotion_words(ch),
            "แรงขับ": desire_words(ch)}


