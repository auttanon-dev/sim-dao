# ไม่ใช่สิ่งที่ใครเลือกเอง — ฟ้าลิขิตให้เกิด ยังคงสุ่มตามน้ำหนักเดิมก่อนถึงตาจิตใจ
INVOLUNTARY = frozenset({"ภัยธรรมชาติ"})


def needs_target(kind: str, table) -> bool:
    for e in table:
        if e["kind"] == kind:
            return bool(e["tgt"])
    return False


def build_menu(weights: dict, table, limit: int):
    """คืนรายการ kind ที่เลือกได้ เรียงจากแรงผลักมากไปน้อย (ตัดข้อที่น้ำหนักเป็นศูนย์และข้อที่ฟ้ากำหนด)"""
    known = {e["kind"] for e in table}
    items = [(k, v) for k, v in weights.items()
             if v > 0 and k in known and k not in INVOLUNTARY]
    items.sort(key=lambda kv: -kv[1])
    menu = [k for k, _ in items[:limit]]
    # ทางเลือกพื้นฐานที่คนเราทำได้เสมอ ถ้าเอนจินอนุญาต แต่หลุดจากอันดับ
    for k in ("บำเพ็ญ", "เดินทาง", "ซ่อนตัว"):
        if k not in menu and weights.get(k, 0) > 0:
            menu.append(k)
    return menu


def normalize_kind(text: str, menu):
    """จับคู่คำตอบของโมเดลกับชื่อในเมนู — ทนต่อช่องว่าง/คำนำหน้า/วงเล็บที่โมเดลชอบเติม"""
    if not text:
        return None
    t = str(text).strip().strip('"').replace(" ", "")
    for k in menu:
        if t == k.replace(" ", ""):
            return k
    for k in sorted(menu, key=len, reverse=True):
        if k.replace(" ", "") in t:
            return k
    return None
