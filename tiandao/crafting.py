def rank_tier(rank):
    return min(2, rank // 3)


def rank_grade(rank):
    """ขั้นช่างในระดับโลกนั้นๆ ทำของได้ถึงเกรดไหน"""
    return rank % 3


def can_make(rank, tier, grade):
    return rank_tier(rank) >= tier and (rank_tier(rank) > tier or rank_grade(rank) >= grade)


